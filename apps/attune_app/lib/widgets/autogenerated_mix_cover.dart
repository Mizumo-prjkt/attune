/// Procedural shapey YouTube Music-style vector/SVG artwork cover
class AutogeneratedMixCover extends StatelessWidget {
  final ForYouMix mix;
  final double size;
  final double borderRadius;
  final ForYouArtStyle? styleOverride;
  final bool showBadge;

  const AutogeneratedMixCover({
    super.key,
    required this.mix,
    this.size = 140.0,
    this.borderRadius = 24.0,
    this.styleOverride,
    this.showBadge = true,
  });

  @override
  Widget build(BuildContext context) {
    final style = styleOverride ?? mix.artStyle;

    return Container(
      width: size,
      height: size,
      decoration: BoxDecoration(
        borderRadius: BorderRadius.circular(borderRadius),
        gradient: LinearGradient(
          begin: Alignment.topLeft,
          end: Alignment.bottomRight,
          colors: [
            mix.primaryColor,
            mix.secondaryColor,
          ],
        ),
      ),
      child: ClipRRect(
        borderRadius: BorderRadius.circular(borderRadius),
        child: Stack(
          fit: StackFit.expand,
          children: [
            // Procedural Vector Artwork
            CustomPaint(
              size: Size(size, size),
              painter: _MixVectorPainter(
                style: style,
                primaryColor: mix.primaryColor,
                secondaryColor: mix.secondaryColor,
              ),
            ),

            // Diagonal Glass Highlight
            CustomPaint(
              size: Size(size, size),
              painter: _CoverGlossPainter(),
            ),

            // Top Badge Pill
            if (showBadge && mix.badge.isNotEmpty)
              Positioned(
                top: 8,
                left: 8,
                child: Container(
                  padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                  decoration: BoxDecoration(
                    color: Colors.black.withValues(alpha: 0.40),
                    borderRadius: BorderRadius.circular(10),
                    border: Border.all(color: Colors.white24, width: 0.5),
                  ),
                  child: Text(
                    mix.badge,
                    style: AttuneTypography.soraBadge(
                      color: Colors.white,
                      fontSize: (size * 0.065).clamp(8.0, 11.0),
                      fontWeight: FontWeight.w700,
                    ),
                  ),
                ),
              ),

            // Bottom Center Title Glyph
            Positioned(
              bottom: 8,
              right: 8,
              child: Container(
                padding: const EdgeInsets.all(6),
                decoration: BoxDecoration(
                  color: Colors.black.withValues(alpha: 0.35),
                  shape: BoxShape.circle,
                  border: Border.all(color: Colors.white24, width: 0.5),
                ),
                child: Icon(
                  Icons.auto_awesome_rounded,
                  color: Colors.white,
                  size: (size * 0.12).clamp(12.0, 18.0),
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

/// CustomPainter rendering YouTube Music-style geometric vector shapes
class _MixVectorPainter extends CustomPainter {
  final ForYouArtStyle style;
  final Color primaryColor;
  final Color secondaryColor;

  _MixVectorPainter({
    required this.style,
    required this.primaryColor,
    required this.secondaryColor,
  });

  @override
  void paint(Canvas canvas, Size size) {
    final w = size.width;
    final h = size.height;

    switch (style) {
      case ForYouArtStyle.geometricPulse:
        _paintGeometricPulse(canvas, w, h);
        break;
      case ForYouArtStyle.sonicWave:
        _paintSonicWave(canvas, w, h);
        break;
      case ForYouArtStyle.radialDisc:
        _paintRadialDisc(canvas, w, h);
        break;
      case ForYouArtStyle.orbitBloom:
        _paintOrbitBloom(canvas, w, h);
        break;
      case ForYouArtStyle.starburst:
        _paintStarburst(canvas, w, h);
        break;
    }
  }

  void _paintGeometricPulse(Canvas canvas, double w, double h) {
    final center = Offset(w * 0.5, h * 0.5);
    final paint = Paint()..style = PaintingStyle.fill;

    // Diamond 1
    canvas.save();
    canvas.translate(center.dx, center.dy);
    canvas.rotate(math.pi / 4);

    paint.color = Colors.white.withValues(alpha: 0.15);
    canvas.drawRRect(
      RRect.fromRectAndRadius(Rect.fromCenter(center: Offset.zero, width: w * 0.65, height: h * 0.65), const Radius.circular(16)),
      paint,
    );

    // Diamond 2
    paint.color = Colors.black.withValues(alpha: 0.20);
    canvas.drawRRect(
      RRect.fromRectAndRadius(Rect.fromCenter(center: Offset.zero, width: w * 0.45, height: h * 0.45), const Radius.circular(12)),
      paint,
    );

    // Diamond 3
    paint.color = Colors.white.withValues(alpha: 0.30);
    canvas.drawRRect(
      RRect.fromRectAndRadius(Rect.fromCenter(center: Offset.zero, width: w * 0.25, height: h * 0.25), const Radius.circular(8)),
      paint,
    );

    canvas.restore();
  }

  void _paintSonicWave(Canvas canvas, double w, double h) {
    final strokePaint = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = w * 0.04
      ..strokeCap = StrokeCap.round;

    for (int i = 0; i < 4; i++) {
      final path = Path();
      final yOffset = h * (0.28 + i * 0.16);
      final amplitude = h * (0.12 - i * 0.02);
      final wavelength = w * 0.85;

      path.moveTo(0, yOffset);
      for (double x = 0; x <= w; x += 4) {
        final y = yOffset + math.sin((x / wavelength) * 2 * math.pi + (i * 0.8)) * amplitude;
        path.lineTo(x, y);
      }

      strokePaint.color = Colors.white.withValues(alpha: 0.12 + (i * 0.08));
      canvas.drawPath(path, strokePaint);
    }
  }

  void _paintRadialDisc(Canvas canvas, double w, double h) {
    final center = Offset(w * 0.5, h * 0.5);
    final strokePaint = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.5;

    // Vinyl grooves
    for (int i = 1; i <= 6; i++) {
      strokePaint.color = Colors.white.withValues(alpha: 0.08 + (i * 0.03));
      canvas.drawCircle(center, (w * 0.45) * (i / 6.0), strokePaint);
    }

    // Center Spindle
    final fillPaint = Paint()
      ..style = PaintingStyle.fill
      ..color = Colors.black.withValues(alpha: 0.35);
    canvas.drawCircle(center, w * 0.14, fillPaint);

    fillPaint.color = Colors.white.withValues(alpha: 0.6);
    canvas.drawCircle(center, w * 0.04, fillPaint);
  }

  void _paintOrbitBloom(Canvas canvas, double w, double h) {
    final paint = Paint()..style = PaintingStyle.fill;
    final center = Offset(w * 0.5, h * 0.5);
    final count = 5;

    for (int i = 0; i < count; i++) {
      final angle = (i * 2 * math.pi / count);
      final offset = Offset(center.dx + math.cos(angle) * (w * 0.22), center.dy + math.sin(angle) * (h * 0.22));

      paint.color = Colors.white.withValues(alpha: 0.14 + (i * 0.04));
      canvas.drawCircle(offset, w * 0.25, paint);
    }
  }

  void _paintStarburst(Canvas canvas, double w, double h) {
    final center = Offset(w * 0.5, h * 0.5);
    final rayPaint = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = w * 0.035
      ..strokeCap = StrokeCap.round;

    final rayCount = 12;
    for (int i = 0; i < rayCount; i++) {
      final angle = (i * 2 * math.pi / rayCount);
      final r1 = w * 0.18;
      final r2 = w * (0.32 + (i % 2 == 0 ? 0.12 : 0.04));

      final p1 = Offset(center.dx + math.cos(angle) * r1, center.dy + math.sin(angle) * r1);
      final p2 = Offset(center.dx + math.cos(angle) * r2, center.dy + math.sin(angle) * r2);

      rayPaint.color = Colors.white.withValues(alpha: i % 2 == 0 ? 0.30 : 0.15);
      canvas.drawLine(p1, p2, rayPaint);
    }

    final centerPaint = Paint()
      ..style = PaintingStyle.fill
      ..color = Colors.white.withValues(alpha: 0.40);
    canvas.drawCircle(center, w * 0.12, centerPaint);
  }

  @override
  bool shouldRepaint(covariant _MixVectorPainter oldDelegate) {
    return oldDelegate.style != style ||
        oldDelegate.primaryColor != primaryColor ||
        oldDelegate.secondaryColor != secondaryColor;
  }
}

/// Gloss overlay for subtle specular sheen across the mix cover
class _CoverGlossPainter extends CustomPainter {
  @override
  void paint(Canvas canvas, Size size) {
    final rect = Rect.fromLTWH(0, 0, size.width, size.height);
    final paint = Paint()
      ..shader = LinearGradient(
        begin: Alignment.topLeft,
        end: Alignment.bottomRight,
        colors: [
          Colors.white.withValues(alpha: 0.18),
          Colors.white.withValues(alpha: 0.0),
        ],
        stops: const [0.0, 0.45],
      ).createShader(rect);

    canvas.drawRect(rect, paint);
  }

  @override
  bool shouldRepaint(covariant CustomPainter oldDelegate) => false;
}
