import 'dart:io';
import 'package:flutter/material.dart';
import '../models/for_you_mix.dart';
import '../models/track_item.dart';
import '../stages/albums_stage.dart';
import '../theme/liquid_glass.dart';
import '../theme/typography.dart';
import 'autogenerated_mix_cover.dart';

/// M3 Expressive Organic Collage Widget conforming to the YouTube Music concept art:
/// - Large slanted lozenge/stadium center hero cutout displaying primary album artwork
/// - Perimeter floating circular bubbles displaying complementary album artworks
/// - Tapping any image navigates to that track's album page
/// - Bundles tracks lacking images into coordinated procedural vector shapes
/// - Supports 3D Parallax Tilt via LiquidGlassContainer
class M3ExpressiveMixCollage extends StatelessWidget {
  final ForYouMix mix;
  final VoidCallback? onPlay;
  final VoidCallback? onOpenNowPlaying;

  const M3ExpressiveMixCollage({
    super.key,
    required this.mix,
    this.onPlay,
    this.onOpenNowPlaying,
  });

  void _navigateToAlbum(BuildContext context, TrackItem track) {
    final albumName = track.album.isNotEmpty ? track.album : track.title;
    Navigator.of(context).push(
      MaterialPageRoute(
        builder: (_) => Scaffold(
          backgroundColor: Colors.transparent,
          body: SafeArea(
            child: AlbumsStage(
              initialSelectedAlbum: albumName,
              onOpenNowPlaying: onOpenNowPlaying,
            ),
          ),
        ),
      ),
    );
  }

  Widget _buildArtworkTile(
    BuildContext context, {
    required TrackItem? track,
    required double width,
    required double height,
    required BorderRadius borderRadius,
    bool isTilted = false,
  }) {
    Widget imageContent;

    if (track != null &&
        track.artworkFile != null &&
        track.artworkFile!.isNotEmpty &&
        File(track.artworkFile!).existsSync()) {
      imageContent = Image.file(
        File(track.artworkFile!),
        width: width,
        height: height,
        fit: BoxFit.cover,
      );
    } else if (track != null &&
        track.artworkAsset != null &&
        track.artworkAsset!.isNotEmpty) {
      imageContent = Image.asset(
        track.artworkAsset!,
        width: width,
        height: height,
        fit: BoxFit.cover,
      );
    } else {
      // Bundled procedural vector graphic for items with no image so it looks intentional
      imageContent = Container(
        width: width,
        height: height,
        decoration: BoxDecoration(
          gradient: LinearGradient(
            begin: Alignment.topLeft,
            end: Alignment.bottomRight,
            colors: [
              mix.primaryColor.withValues(alpha: 0.85),
              mix.secondaryColor.withValues(alpha: 0.70),
            ],
          ),
        ),
        child: AutogeneratedMixCover(
          mix: mix,
          size: width.clamp(50, 260),
        ),
      );
    }

    Widget content = ClipRRect(
      borderRadius: borderRadius,
      child: imageContent,
    );

    // Subtle dark border and specular rim around collage cuts
    content = Container(
      width: width,
      height: height,
      decoration: BoxDecoration(
        borderRadius: borderRadius,
        border: Border.all(
          color: Colors.white.withValues(alpha: 0.20),
          width: 1.5,
        ),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withValues(alpha: 0.35),
            blurRadius: 16,
            offset: const Offset(0, 8),
          ),
        ],
      ),
      child: content,
    );

    if (track != null) {
      content = GestureDetector(
        onTap: () => _navigateToAlbum(context, track),
        behavior: HitTestBehavior.opaque,
        child: Tooltip(
          message: 'View album: ${track.album.isNotEmpty ? track.album : track.title}',
          child: content,
        ),
      );
    }

    return content;
  }

  @override
  Widget build(BuildContext context) {
    final colorScheme = Theme.of(context).colorScheme;
    final tracks = mix.tracks;

    // Pick up to 5 tracks for the collage
    final heroTrack = tracks.isNotEmpty ? tracks[0] : null;
    final bubble1Track = tracks.length > 1 ? tracks[1] : null;
    final bubble2Track = tracks.length > 2 ? tracks[2] : null;
    final bubble3Track = tracks.length > 3 ? tracks[3] : null;
    final bubble4Track = tracks.length > 4 ? tracks[4] : null;

    // Dynamic subtitle text listing top artists
    final artists = tracks
        .map((t) => t.artist)
        .where((a) => a.isNotEmpty && a != 'Unknown Artist')
        .toSet()
        .take(3)
        .join(', ');
    final subtitleText = artists.isNotEmpty
        ? artists
        : '${tracks.length} curated tracks • ${mix.vibeCategory.toUpperCase()}';

    return LiquidGlassContainer(
      enableTilt: true,
      borderRadius: 32,
      surfaceAlpha: 0.12,
      padding: const EdgeInsets.symmetric(horizontal: 20.0, vertical: 22.0),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          // 1. Header with Title, Subtitle, and Prominent Circular Play Button
          Row(
            crossAxisAlignment: CrossAxisAlignment.center,
            children: [
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      mix.title,
                      style: AttuneTypography.soraDisplayLarge(
                        fontSize: 34,
                        fontWeight: FontWeight.w800,
                        color: colorScheme.onSurface,
                      ),
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                    ),
                    const SizedBox(height: 4),
                    Text(
                      subtitleText,
                      style: AttuneTypography.jakartaBody(
                        fontSize: 13,
                        fontWeight: FontWeight.w500,
                        color: colorScheme.onSurface.withValues(alpha: 0.65),
                      ),
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                    ),
                  ],
                ),
              ),
              const SizedBox(width: 14),

              // Large Pastel Circular Play Button
              GestureDetector(
                onTap: onPlay,
                behavior: HitTestBehavior.opaque,
                child: Container(
                  width: 72,
                  height: 72,
                  decoration: BoxDecoration(
                    shape: BoxShape.circle,
                    color: const Color(0xFFB4D2FE), // Pastel M3 blue from concept
                    boxShadow: [
                      BoxShadow(
                        color: const Color(0xFFB4D2FE).withValues(alpha: 0.35),
                        blurRadius: 18,
                        offset: const Offset(0, 6),
                      ),
                    ],
                  ),
                  child: const Center(
                    child: Icon(
                      Icons.play_arrow_rounded,
                      size: 42,
                      color: Color(0xFF101418),
                    ),
                  ),
                ),
              ),
            ],
          ),

          const SizedBox(height: 24),

          // 2. Centerpiece Expressive Collage (Organic Masks)
          Center(
            child: SizedBox(
              width: 330,
              height: 380,
              child: Stack(
                clipBehavior: Clip.none,
                alignment: Alignment.center,
                children: [
                  // HERO: Large slanted stadium/lozenge shape (-26 degrees)
                  Positioned(
                    top: 25,
                    child: Transform.rotate(
                      angle: -0.45, // -26 degrees tilt
                      child: _buildArtworkTile(
                        context,
                        track: heroTrack,
                        width: 200,
                        height: 295,
                        borderRadius: BorderRadius.circular(105),
                        isTilted: true,
                      ),
                    ),
                  ),

                  // BUBBLE 1: Top-Left Circle
                  Positioned(
                    top: 18,
                    left: 10,
                    child: _buildArtworkTile(
                      context,
                      track: bubble1Track,
                      width: 76,
                      height: 76,
                      borderRadius: BorderRadius.circular(38),
                    ),
                  ),

                  // BUBBLE 2: Top-Right Circle
                  Positioned(
                    top: 48,
                    right: 8,
                    child: _buildArtworkTile(
                      context,
                      track: bubble2Track,
                      width: 82,
                      height: 82,
                      borderRadius: BorderRadius.circular(41),
                    ),
                  ),

                  // BUBBLE 3: Bottom-Right Circle
                  Positioned(
                    bottom: 22,
                    right: 18,
                    child: _buildArtworkTile(
                      context,
                      track: bubble3Track,
                      width: 90,
                      height: 90,
                      borderRadius: BorderRadius.circular(45),
                    ),
                  ),

                  // BUBBLE 4: Bottom-Left Circle
                  Positioned(
                    bottom: 8,
                    left: 28,
                    child: _buildArtworkTile(
                      context,
                      track: bubble4Track,
                      width: 68,
                      height: 68,
                      borderRadius: BorderRadius.circular(34),
                    ),
                  ),
                ],
              ),
            ),
          ),

          const SizedBox(height: 12),

          // 3. Collage Navigation Hint
          Center(
            child: Row(
              mainAxisSize: MainAxisSize.min,
              children: [
                Icon(
                  Icons.touch_app_rounded,
                  size: 14,
                  color: colorScheme.onSurface.withValues(alpha: 0.4),
                ),
                const SizedBox(width: 6),
                Text(
                  'Tap any artwork to open its album page',
                  style: AttuneTypography.jakartaBodySmall(
                    fontSize: 11,
                    color: colorScheme.onSurface.withValues(alpha: 0.45),
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }
}
