import 'dart:io';
import 'package:flutter/material.dart';
import '../models/track_item.dart';
import '../services/for_you_service.dart';
import '../services/playback_controller.dart';
import '../services/settings_service.dart';
import '../l10n/translation_core.dart';
import '../theme/liquid_glass.dart';
import '../theme/typography.dart';
import '../widgets/autogenerated_mix_cover.dart';
import 'home_customization_stage.dart';

/// HomeStage: The customizable primary landing and browsing hub of Attune.
/// Features dynamic, non-hardcoded section rendering (ordered and toggled via Settings),
/// autogenerated YouTube Music-style shapey vibe mixes, dynamic genre chips,
/// quick picks, and discovered tracks.
class HomeStage extends StatefulWidget {
  final VoidCallback? onOpenNowPlaying;

  const HomeStage({super.key, this.onOpenNowPlaying});

  @override
  State<HomeStage> createState() => _HomeStageState();
}

class _HomeStageState extends State<HomeStage> {
  int _selectedFilter = 0;
  final TextEditingController _searchController = TextEditingController();
  String _searchQuery = '';

  @override
  void dispose() {
    _searchController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final colorScheme = Theme.of(context).colorScheme;

    return ListenableBuilder(
      listenable: Listenable.merge([
        PlaybackController.instance,
        SettingsService.instance,
        AppLocalizations.instance,
      ]),
      builder: (context, _) {
        final controller = PlaybackController.instance;
        final allTracks = controller.libraryTracks;
        final currentTrack = controller.currentTrack;
        final settings = SettingsService.instance;
        final homeSections = settings.homeSections;

        // Dynamic genres extracted from actual library tracks
        final discoveredGenres = allTracks
            .map((t) => t.genre)
            .where((g) => g.isNotEmpty && g != 'General')
            .toSet()
            .toList();
        discoveredGenres.sort();
        final dynamicFilters = [context.tr('home_filter_all'), ...discoveredGenres];

        // Ensure filter index in bounds
        if (_selectedFilter >= dynamicFilters.length) {
          _selectedFilter = 0;
        }

        // Apply search query filter
        var filteredTracks = allTracks.where((t) {
          if (_searchQuery.isEmpty) return true;
          final q = _searchQuery.toLowerCase();
          return t.title.toLowerCase().contains(q) ||
              t.artist.toLowerCase().contains(q) ||
              t.album.toLowerCase().contains(q);
        }).toList();

        // Apply dynamic genre filter
        if (_selectedFilter > 0 && _selectedFilter < dynamicFilters.length) {
          final selectedGenre = dynamicFilters[_selectedFilter].toLowerCase();
          filteredTracks = filteredTracks.where((t) {
            return t.genre.toLowerCase() == selectedGenre ||
                t.title.toLowerCase().contains(selectedGenre);
          }).toList();
        }

        // Build list of widgets dynamically based on user-customized sections
        final sectionWidgets = <Widget>[];

        for (final section in homeSections) {
          if (!section.enabled) continue;

          switch (section.id) {
            case 'search_bar':
              sectionWidgets.add(_buildSearchBar(colorScheme, controller, allTracks));
              sectionWidgets.add(const SizedBox(height: 14));
              break;

            case 'for_you_mixes':
              sectionWidgets.add(_buildForYouMixes(context, colorScheme, controller, allTracks));
              sectionWidgets.add(const SizedBox(height: 18));
              break;

            case 'genre_chips':
              if (dynamicFilters.length > 1) {
                sectionWidgets.add(_buildGenreChips(colorScheme, dynamicFilters));
                sectionWidgets.add(const SizedBox(height: 18));
              }
              break;

            case 'quick_picks':
              sectionWidgets.add(_buildQuickPicks(colorScheme, controller, allTracks));
              sectionWidgets.add(const SizedBox(height: 20));
              break;

            case 'recent_tracks':
              if (allTracks.isNotEmpty) {
                sectionWidgets.add(_buildRecentTracks(colorScheme, controller, allTracks));
                sectionWidgets.add(const SizedBox(height: 20));
              }
              break;

            case 'all_tracks':
              sectionWidgets.add(_buildAllTracks(colorScheme, controller, filteredTracks, allTracks, currentTrack));
              sectionWidgets.add(const SizedBox(height: 20));
              break;
          }
        }

        return ListView(
          physics: const BouncingScrollPhysics(),
          padding: const EdgeInsets.symmetric(horizontal: 20.0, vertical: 16.0),
          children: [
            ...sectionWidgets,
            const SizedBox(height: 80),
          ],
        );
      },
    );
  }

  // --- Dynamic Section Builders ---

  Widget _buildSearchBar(ColorScheme colorScheme, PlaybackController controller, List<TrackItem> allTracks) {
    return LiquidGlassContainer(
      padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 6),
      borderRadius: 24,
      surfaceAlpha: 0.14,
      child: Row(
        children: [
          Icon(Icons.search_rounded, color: colorScheme.onSurface.withValues(alpha: 0.6), size: 22),
          const SizedBox(width: 12),
          Expanded(
            child: TextField(
              controller: _searchController,
              style: AttuneTypography.jakartaBodyMedium(color: colorScheme.onSurface),
              decoration: InputDecoration(
                hintText: context.tr('home_search_hint', {'count': allTracks.length}),
                hintStyle: AttuneTypography.jakartaBody(
                  color: colorScheme.onSurface.withValues(alpha: 0.4),
                ),
                border: InputBorder.none,
                isDense: true,
              ),
              onChanged: (val) => setState(() => _searchQuery = val),
            ),
          ),
          if (_searchQuery.isNotEmpty)
            GestureDetector(
              onTap: () {
                _searchController.clear();
                setState(() => _searchQuery = '');
              },
              child: Icon(Icons.clear_rounded, size: 20, color: colorScheme.onSurface.withValues(alpha: 0.5)),
            )
          else ...[
            GestureDetector(
              onTap: () => controller.scanLocalAudioDirectories(forceRefresh: true),
              child: Icon(
                Icons.refresh_rounded,
                size: 20,
                color: controller.isScanning
                    ? colorScheme.primary
                    : colorScheme.onSurface.withValues(alpha: 0.4),
              ),
            ),
            const SizedBox(width: 10),
            // Non-popup Home customization trigger
            GestureDetector(
              onTap: () {
                Navigator.of(context).push(
                  MaterialPageRoute(builder: (_) => const HomeCustomizationStage()),
                );
              },
              child: Tooltip(
                message: context.tr('home_customize_tooltip'),
                child: Icon(
                  Icons.tune_rounded,
                  size: 20,
                  color: colorScheme.primary,
                ),
              ),
            ),
          ],
        ],
      ),
    );
  }

  Widget _buildForYouMixes(BuildContext context, ColorScheme colorScheme, PlaybackController controller, List<TrackItem> allTracks) {
    final mixes = ForYouService.instance.generateMixes(context, allTracks);

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          children: [
            Expanded(
              child: Row(
                children: [
                  Icon(Icons.auto_awesome_rounded, size: 16, color: colorScheme.primary),
                  const SizedBox(width: 6),
                  Flexible(
                    child: Text(
                      context.tr('home_section_for_you'),
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                      style: AttuneTypography.soraBadge(
                        color: colorScheme.primary,
                        fontWeight: FontWeight.w700,
                      ),
                    ),
                  ),
                ],
              ),
            ),
            const SizedBox(width: 8),
            GestureDetector(
              onTap: () {
                Navigator.of(context).push(
                  MaterialPageRoute(builder: (_) => const HomeCustomizationStage()),
                );
              },
              child: Row(
                mainAxisSize: MainAxisSize.min,
                children: [
                  Icon(Icons.tune_rounded, size: 12, color: colorScheme.onSurface.withValues(alpha: 0.5)),
                  const SizedBox(width: 4),
                  Text(
                    context.tr('home_customize'),
                    style: AttuneTypography.soraBadge(
                      color: colorScheme.onSurface.withValues(alpha: 0.5),
                    ),
                  ),
                ],
              ),
            ),
          ],
        ),
        const SizedBox(height: 10),
        SizedBox(
          height: 195,
          child: ListView.separated(
            scrollDirection: Axis.horizontal,
            physics: const BouncingScrollPhysics(),
            itemCount: mixes.length,
            separatorBuilder: (_, _) => const SizedBox(width: 14),
            itemBuilder: (context, index) {
              final mix = mixes[index];
              return GestureDetector(
                onTap: () => ForYouService.instance.playMix(mix, onOpenNowPlaying: widget.onOpenNowPlaying),
                child: SizedBox(
                  width: 140,
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      AutogeneratedMixCover(
                        mix: mix,
                        size: 140,
                        borderRadius: 22,
                      ),
                      const SizedBox(height: 8),
                      Text(
                        mix.title,
                        style: AttuneTypography.soraSubheading(
                          fontSize: 13,
                          fontWeight: FontWeight.w600,
                          color: colorScheme.onSurface,
                        ),
                        maxLines: 1,
                        overflow: TextOverflow.ellipsis,
                      ),
                      const SizedBox(height: 2),
                      Text(
                        mix.subtitle,
                        style: AttuneTypography.jakartaBodySmall(
                          color: colorScheme.onSurface.withValues(alpha: 0.55),
                          fontSize: 11,
                        ),
                        maxLines: 1,
                        overflow: TextOverflow.ellipsis,
                      ),
                    ],
                  ),
                ),
              );
            },
          ),
        ),
      ],
    );
  }

  Widget _buildGenreChips(ColorScheme colorScheme, List<String> filters) {
    return SizedBox(
      height: 36,
      child: ListView.separated(
        scrollDirection: Axis.horizontal,
        physics: const BouncingScrollPhysics(),
        itemCount: filters.length,
        separatorBuilder: (_, _) => const SizedBox(width: 8),
        itemBuilder: (context, index) {
          final isSelected = _selectedFilter == index;
          return GestureDetector(
            onTap: () => setState(() => _selectedFilter = index),
            child: LiquidGlassContainer(
              padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 8),
              borderRadius: 18,
              surfaceAlpha: isSelected ? 0.32 : 0.08,
              borderColor: isSelected ? colorScheme.primary.withValues(alpha: 0.6) : null,
              child: Center(
                child: Text(
                  filters[index],
                  style: AttuneTypography.soraBadge(
                    color: isSelected ? colorScheme.primary : colorScheme.onSurface.withValues(alpha: 0.7),
                    fontWeight: isSelected ? FontWeight.w700 : FontWeight.w500,
                  ),
                ),
              ),
            ),
          );
        },
      ),
    );
  }

  Widget _buildQuickPicks(ColorScheme colorScheme, PlaybackController controller, List<TrackItem> allTracks) {
    return Row(
      children: [
        Expanded(
          child: _buildQuickCard(
            title: context.tr('home_quick_picks'),
            subtitle: context.tr('home_total_tracks', {'count': allTracks.length}),
            icon: Icons.favorite_rounded,
            accentColor: colorScheme.primary,
            colorScheme: colorScheme,
            onTap: () {
              if (allTracks.isNotEmpty) {
                controller.playTrack(allTracks.first);
                widget.onOpenNowPlaying?.call();
              }
            },
          ),
        ),
        const SizedBox(width: 12),
        Expanded(
          child: _buildQuickCard(
            title: context.tr('home_heavy_rotation'),
            subtitle: allTracks.isNotEmpty ? allTracks.first.genre : 'Attune Mix',
            icon: Icons.bolt_rounded,
            accentColor: colorScheme.tertiary,
            colorScheme: colorScheme,
            onTap: () {
              final energeticTracks = allTracks.where((t) => t.effectiveBpm >= 120 || t.genre == 'Rock').toList();
              if (energeticTracks.isNotEmpty) {
                controller.playTrack(energeticTracks.first);
                widget.onOpenNowPlaying?.call();
              } else if (allTracks.isNotEmpty) {
                controller.playTrack(allTracks.first);
                widget.onOpenNowPlaying?.call();
              }
            },
          ),
        ),
      ],
    );
  }

  Widget _buildRecentTracks(ColorScheme colorScheme, PlaybackController controller, List<TrackItem> allTracks) {
    final recent = allTracks.take(4).toList();

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(
          context.tr('home_section_recent'),
          style: AttuneTypography.soraBadge(
            color: colorScheme.primary,
            fontWeight: FontWeight.w700,
          ),
        ),
        const SizedBox(height: 10),
        SizedBox(
          height: 74,
          child: ListView.separated(
            scrollDirection: Axis.horizontal,
            physics: const BouncingScrollPhysics(),
            itemCount: recent.length,
            separatorBuilder: (_, _) => const SizedBox(width: 10),
            itemBuilder: (context, index) {
              final track = recent[index];
              return GestureDetector(
                onTap: () {
                  controller.playTrack(track);
                  widget.onOpenNowPlaying?.call();
                },
                child: LiquidGlassContainer(
                  width: 200,
                  padding: const EdgeInsets.all(10),
                  borderRadius: 18,
                  surfaceAlpha: 0.10,
                  child: Row(
                    children: [
                      Container(
                        width: 44,
                        height: 44,
                        decoration: BoxDecoration(
                          borderRadius: BorderRadius.circular(12),
                          gradient: LinearGradient(
                            colors: [track.seedColor.withValues(alpha: 0.7), track.seedColor.withValues(alpha: 0.3)],
                          ),
                        ),
                        child: ClipRRect(
                          borderRadius: BorderRadius.circular(12),
                          child: track.artworkFile != null && File(track.artworkFile!).existsSync()
                              ? Image.file(File(track.artworkFile!), fit: BoxFit.cover)
                              : const Icon(Icons.music_note_rounded, color: Colors.white70, size: 20),
                        ),
                      ),
                      const SizedBox(width: 10),
                      Expanded(
                        child: Column(
                          mainAxisAlignment: MainAxisAlignment.center,
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            Text(
                              track.title,
                              style: AttuneTypography.soraSubheading(fontSize: 12, fontWeight: FontWeight.w600, color: colorScheme.onSurface),
                              maxLines: 1,
                              overflow: TextOverflow.ellipsis,
                            ),
                            Text(
                              track.artist,
                              style: AttuneTypography.jakartaBodySmall(fontSize: 11, color: colorScheme.onSurface.withValues(alpha: 0.6)),
                              maxLines: 1,
                              overflow: TextOverflow.ellipsis,
                            ),
                          ],
                        ),
                      ),
                    ],
                  ),
                ),
              );
            },
          ),
        ),
      ],
    );
  }

  Widget _buildAllTracks(
    ColorScheme colorScheme,
    PlaybackController controller,
    List<TrackItem> filteredTracks,
    List<TrackItem> allTracks,
    TrackItem? currentTrack,
  ) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          mainAxisAlignment: MainAxisAlignment.spaceBetween,
          children: [
            Expanded(
              child: Text(
                context.tr('home_discovered_tracks', {'count': filteredTracks.length}),
                style: AttuneTypography.soraBadge(
                  color: colorScheme.primary,
                  fontWeight: FontWeight.w700,
                ),
                maxLines: 1,
                overflow: TextOverflow.ellipsis,
              ),
            ),
            const SizedBox(width: 8),
            Text(
              context.tr('home_total_tracks', {'count': allTracks.length}),
              style: AttuneTypography.soraBadge(
                color: colorScheme.onSurface.withValues(alpha: 0.4),
              ),
            ),
          ],
        ),
        const SizedBox(height: 12),
        if (filteredTracks.isEmpty)
          Padding(
            padding: const EdgeInsets.symmetric(vertical: 40),
            child: Center(
              child: Text(
                _searchQuery.isNotEmpty
                    ? context.tr('home_no_tracks_found', {'query': _searchQuery})
                    : context.tr('home_no_tracks_empty'),
                style: AttuneTypography.jakartaBody(
                  color: colorScheme.onSurface.withValues(alpha: 0.5),
                ),
                textAlign: TextAlign.center,
              ),
            ),
          )
        else
          ListView.separated(
            shrinkWrap: true,
            physics: const NeverScrollableScrollPhysics(),
            itemCount: filteredTracks.length,
            separatorBuilder: (_, _) => const SizedBox(height: 8),
            itemBuilder: (context, index) {
              final track = filteredTracks[index];
              final isCurrent = currentTrack?.id == track.id;
              final isPlaying = isCurrent && controller.isPlaying;

              return _buildTrackRow(
                track: track,
                isCurrent: isCurrent,
                isPlaying: isPlaying,
                colorScheme: colorScheme,
                onTap: () {
                  controller.playTrack(track);
                  widget.onOpenNowPlaying?.call();
                },
              );
            },
          ),
      ],
    );
  }

  Widget _buildQuickCard({
    required String title,
    required String subtitle,
    required IconData icon,
    required Color accentColor,
    required ColorScheme colorScheme,
    required VoidCallback onTap,
  }) {
    return GestureDetector(
      onTap: onTap,
      behavior: HitTestBehavior.opaque,
      child: LiquidGlassContainer(
        padding: const EdgeInsets.all(16),
        borderRadius: 22,
        surfaceAlpha: 0.12,
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Container(
              padding: const EdgeInsets.all(10),
              decoration: BoxDecoration(
                color: accentColor.withValues(alpha: 0.15),
                shape: BoxShape.circle,
              ),
              child: Icon(icon, color: accentColor, size: 22),
            ),
            const SizedBox(height: 14),
            Text(
              title,
              style: AttuneTypography.soraSubheading(
                fontWeight: FontWeight.w600,
                color: colorScheme.onSurface,
              ),
            ),
            const SizedBox(height: 3),
            Text(
              subtitle,
              style: AttuneTypography.jakartaBody(
                color: colorScheme.onSurface.withValues(alpha: 0.5),
                fontSize: 12,
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildTrackRow({
    required TrackItem track,
    required bool isCurrent,
    required bool isPlaying,
    required ColorScheme colorScheme,
    required VoidCallback onTap,
  }) {
    final minutes = track.duration.inMinutes;
    final seconds = track.duration.inSeconds % 60;
    final durationStr = '$minutes:${seconds.toString().padLeft(2, '0')}';

    return GestureDetector(
      onTap: onTap,
      behavior: HitTestBehavior.opaque,
      child: LiquidGlassContainer(
        padding: const EdgeInsets.all(12),
        borderRadius: 18,
        surfaceAlpha: isCurrent ? 0.26 : 0.08,
        borderColor: isCurrent ? colorScheme.primary.withValues(alpha: 0.5) : null,
        child: Row(
          children: [
            // Album Art Thumbnail
            Container(
              width: 48,
              height: 48,
              decoration: BoxDecoration(
                borderRadius: BorderRadius.circular(12),
                gradient: LinearGradient(
                  colors: [track.seedColor.withValues(alpha: 0.6), track.seedColor.withValues(alpha: 0.2)],
                  begin: Alignment.topLeft,
                  end: Alignment.bottomRight,
                ),
              ),
              child: ClipRRect(
                borderRadius: BorderRadius.circular(12),
                child: track.artworkFile != null && File(track.artworkFile!).existsSync()
                    ? Image.file(
                        File(track.artworkFile!),
                        fit: BoxFit.cover,
                      )
                    : const Icon(
                        Icons.music_note_rounded,
                        color: Colors.white70,
                        size: 24,
                      ),
              ),
            ),

            const SizedBox(width: 14),

            // Track Title and Artist
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(
                    children: [
                      if (isCurrent) ...[
                        Icon(Icons.play_arrow_rounded, color: colorScheme.primary, size: 16),
                        const SizedBox(width: 4),
                      ],
                      Expanded(
                        child: Text(
                          track.title,
                          maxLines: 1,
                          overflow: TextOverflow.ellipsis,
                          style: AttuneTypography.soraSubheading(
                            fontWeight: FontWeight.w600,
                            color: isCurrent ? colorScheme.primary : colorScheme.onSurface,
                          ),
                        ),
                      ),
                    ],
                  ),
                  const SizedBox(height: 3),
                  Text(
                    '${track.artist} • ${track.format}${track.hasBpm ? " • ${track.formattedBpm}" : ""}',
                    maxLines: 1,
                    overflow: TextOverflow.ellipsis,
                    style: AttuneTypography.jakartaBody(
                      color: colorScheme.onSurface.withValues(alpha: 0.55),
                      fontSize: 12,
                    ),
                  ),
                ],
              ),
            ),

            const SizedBox(width: 12),

            // Duration & Play State
            Text(
              durationStr,
              style: AttuneTypography.soraBadge(
                color: colorScheme.onSurface.withValues(alpha: 0.5),
              ),
            ),
            const SizedBox(width: 10),
            Icon(
              isPlaying ? Icons.pause_circle_filled_rounded : Icons.play_circle_fill_rounded,
              color: isCurrent ? colorScheme.primary : colorScheme.onSurface.withValues(alpha: 0.4),
              size: 24,
            ),
          ],
        ),
      ),
    );
  }
}
