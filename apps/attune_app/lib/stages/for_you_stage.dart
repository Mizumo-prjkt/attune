import 'package:flutter/material.dart';
import '../models/for_you_mix.dart';
import '../models/track_item.dart';
import '../services/for_you_service.dart';
import '../services/playback_controller.dart';
import '../services/settings_service.dart';
import '../stages/albums_stage.dart';
import '../stages/autogen_mix_stage.dart';
import '../stages/bubble_navigation_stage.dart';
import '../l10n/translation_core.dart';
import '../theme/liquid_glass.dart';
import '../theme/typography.dart';
import '../widgets/autogenerated_mix_cover.dart';
import '../widgets/m3_expressive_mix_collage.dart';

/// ForYouStage: Autogenerated YouTube Music-style algorithmic mixes
/// with M3 Expressive organic artwork collage and optional Beta Algorithmic Cards view.
class ForYouStage extends StatefulWidget {
  final VoidCallback? onOpenNowPlaying;

  const ForYouStage({super.key, this.onOpenNowPlaying});

  @override
  State<ForYouStage> createState() => _ForYouStageState();
}

class _ForYouStageState extends State<ForYouStage> {
  ForYouArtStyle? _selectedStyleOverride;
  int _selectedMixIndex = 0;

  void _navigateToAlbum(BuildContext context, TrackItem track) {
    final albumName = track.album.isNotEmpty ? track.album : track.title;
    Navigator.of(context).push(
      MaterialPageRoute(
        builder: (_) => Scaffold(
          backgroundColor: Colors.transparent,
          body: SafeArea(
            child: AlbumsStage(
              initialSelectedAlbum: albumName,
              onOpenNowPlaying: widget.onOpenNowPlaying,
            ),
          ),
        ),
      ),
    );
  }

  void _navigateToMixAlbum(BuildContext context, ForYouMix mix) {
    Navigator.of(context).push(
      MaterialPageRoute(
        builder: (_) => AutogenMixStage(
          mix: mix,
          onOpenNowPlaying: widget.onOpenNowPlaying,
          styleOverride: _selectedStyleOverride,
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final colorScheme = Theme.of(context).colorScheme;

    return ListenableBuilder(
      listenable: Listenable.merge([
        PlaybackController.instance,
        AppLocalizations.instance,
        SettingsService.instance,
      ]),
      builder: (context, _) {
        final controller = PlaybackController.instance;
        final settings = SettingsService.instance;
        final libraryTracks = controller.libraryTracks;
        final mixes = ForYouService.instance.generateMixes(context, libraryTracks);
        final designMode = settings.forYouDesignMode;

        if (_selectedMixIndex >= mixes.length) {
          _selectedMixIndex = 0;
        }
        final activeMix = mixes.isNotEmpty ? mixes[_selectedMixIndex] : null;

        return ListView(
          physics: const BouncingScrollPhysics(),
          padding: const EdgeInsets.symmetric(horizontal: 20.0, vertical: 16.0),
          children: [
            // 1. Stage Header with Design Mode Switcher
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(
                        context.tr('for_you_title'),
                        style: AttuneTypography.soraHeading(
                          color: colorScheme.onSurface,
                          fontWeight: FontWeight.w700,
                        ),
                      ),
                      const SizedBox(height: 2),
                      Text(
                        context.tr('for_you_subtitle'),
                        style: AttuneTypography.jakartaBodySmall(
                          color: colorScheme.onSurface.withValues(alpha: 0.6),
                        ),
                        maxLines: 1,
                        overflow: TextOverflow.ellipsis,
                      ),
                    ],
                  ),
                ),
                const SizedBox(width: 8),

                // Bubblegrid Selection Trigger
                IconButton.filledTonal(
                  icon: const Icon(Icons.bubble_chart_rounded, size: 20),
                  tooltip: context.tr('bubble_nav_title'),
                  onPressed: () {
                    Navigator.of(context).push(
                      MaterialPageRoute(
                        builder: (_) => BubbleNavigationStage(
                          onOpenNowPlaying: widget.onOpenNowPlaying,
                        ),
                      ),
                    );
                  },
                ),
                const SizedBox(width: 8),

                // Design Mode Toggle (M3 Expressive vs Beta Cards)
                Container(
                  decoration: BoxDecoration(
                    color: Colors.white.withValues(alpha: 0.08),
                    borderRadius: BorderRadius.circular(20),
                    border: Border.all(color: Colors.white12),
                  ),
                  child: Row(
                    mainAxisSize: MainAxisSize.min,
                    children: [
                      _buildDesignTab(
                        label: 'M3 Concept',
                        isSelected: designMode == ForYouDesignMode.m3Expressive,
                        onTap: () => settings.setForYouDesignMode(ForYouDesignMode.m3Expressive),
                        colorScheme: colorScheme,
                      ),
                      _buildDesignTab(
                        label: 'Beta Cards',
                        isSelected: designMode == ForYouDesignMode.betaCards,
                        onTap: () => settings.setForYouDesignMode(ForYouDesignMode.betaCards),
                        colorScheme: colorScheme,
                      ),
                    ],
                  ),
                ),
              ],
            ),

            const SizedBox(height: 18),

            // ==========================================
            // DESIGN MODE A: M3 EXPRESSIVE CONCEPT
            // ==========================================
            if (designMode == ForYouDesignMode.m3Expressive && activeMix != null) ...[
              // Mix Selector Pills
              SizedBox(
                height: 38,
                child: ListView.separated(
                  scrollDirection: Axis.horizontal,
                  physics: const BouncingScrollPhysics(),
                  itemCount: mixes.length,
                  separatorBuilder: (_, _) => const SizedBox(width: 8),
                  itemBuilder: (context, idx) {
                    final mix = mixes[idx];
                    final isSelected = _selectedMixIndex == idx;

                    return ChoiceChip(
                      label: Text(
                        mix.title,
                        style: AttuneTypography.soraBadge(
                          color: isSelected ? Colors.black87 : colorScheme.onSurface.withValues(alpha: 0.75),
                          fontWeight: isSelected ? FontWeight.w700 : FontWeight.w500,
                        ),
                      ),
                      selected: isSelected,
                      selectedColor: const Color(0xFFB4D2FE),
                      backgroundColor: Colors.white.withValues(alpha: 0.06),
                      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(18)),
                      side: BorderSide(
                        color: isSelected ? const Color(0xFFB4D2FE) : Colors.white12,
                      ),
                      onSelected: (_) => setState(() => _selectedMixIndex = idx),
                    );
                  },
                ),
              ),

              const SizedBox(height: 18),

              // M3 Expressive Organic Collage
              M3ExpressiveMixCollage(
                mix: activeMix,
                onPlay: () => ForYouService.instance.playMix(
                  activeMix,
                  onOpenNowPlaying: widget.onOpenNowPlaying,
                ),
                onOpenNowPlaying: widget.onOpenNowPlaying,
                onOpenMixAlbum: () => _navigateToMixAlbum(context, activeMix),
              ),

              const SizedBox(height: 20),

              // Tracks in this Mix
              Text(
                'MIX TRACKLIST (${activeMix.tracks.length})',
                style: AttuneTypography.soraSectionHeader(
                  color: colorScheme.primary,
                  fontWeight: FontWeight.w700,
                ),
              ),
              const SizedBox(height: 10),

              LiquidGlassContainer(
                borderRadius: 24,
                surfaceAlpha: 0.10,
                padding: const EdgeInsets.symmetric(vertical: 8.0),
                child: Column(
                  children: activeMix.tracks.asMap().entries.map((entry) {
                    final idx = entry.key;
                    final track = entry.value;

                    return ListTile(
                      contentPadding: const EdgeInsets.symmetric(horizontal: 16, vertical: 2),
                      leading: SizedBox(
                        width: 32,
                        child: Center(
                          child: Text(
                            '${idx + 1}',
                            style: AttuneTypography.soraMetric(
                              fontSize: 12,
                              color: colorScheme.onSurface.withValues(alpha: 0.4),
                            ),
                          ),
                        ),
                      ),
                      title: Text(
                        track.title,
                        style: AttuneTypography.jakartaBodyLarge(
                          color: colorScheme.onSurface,
                          fontWeight: FontWeight.w600,
                          fontSize: 14,
                        ),
                        maxLines: 1,
                        overflow: TextOverflow.ellipsis,
                      ),
                      subtitle: Text(
                        track.artist.isNotEmpty ? track.artist : 'Unknown Artist',
                        style: AttuneTypography.jakartaBodySmall(
                          color: colorScheme.onSurface.withValues(alpha: 0.6),
                          fontSize: 12,
                        ),
                        maxLines: 1,
                        overflow: TextOverflow.ellipsis,
                      ),
                      trailing: Row(
                        mainAxisSize: MainAxisSize.min,
                        children: [
                          IconButton(
                            icon: const Icon(Icons.album_rounded, size: 18),
                            tooltip: 'View Album',
                            color: colorScheme.onSurface.withValues(alpha: 0.5),
                            onPressed: () => _navigateToAlbum(context, track),
                          ),
                          IconButton(
                            icon: Icon(Icons.play_circle_fill_rounded, size: 24, color: colorScheme.primary),
                            tooltip: 'Play',
                            onPressed: () {
                              controller.playTrack(track);
                              widget.onOpenNowPlaying?.call();
                            },
                          ),
                        ],
                      ),
                    );
                  }).toList(),
                ),
              ),
            ]

            // ==========================================
            // DESIGN MODE B: BETA ALGORITHMIC CARDS
            // ==========================================
            else ...[
              // Interactive Sample Art Style Switcher
              SizedBox(
                height: 38,
                child: ListView.separated(
                  scrollDirection: Axis.horizontal,
                  physics: const BouncingScrollPhysics(),
                  itemCount: ForYouArtStyle.values.length + 1,
                  separatorBuilder: (_, _) => const SizedBox(width: 8),
                  itemBuilder: (context, index) {
                    if (index == 0) {
                      final isSelected = _selectedStyleOverride == null;
                      return ChoiceChip(
                        label: Text('Auto Dynamic', style: AttuneTypography.soraBadge(color: isSelected ? colorScheme.primary : colorScheme.onSurface.withValues(alpha: 0.7))),
                        selected: isSelected,
                        selectedColor: colorScheme.primary.withValues(alpha: 0.22),
                        backgroundColor: Colors.white.withValues(alpha: 0.06),
                        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(18)),
                        side: BorderSide(color: isSelected ? colorScheme.primary.withValues(alpha: 0.5) : Colors.white12),
                        onSelected: (_) => setState(() => _selectedStyleOverride = null),
                      );
                    }

                    final style = ForYouArtStyle.values[index - 1];
                    final isSelected = _selectedStyleOverride == style;

                    return ChoiceChip(
                      label: Text(style.label, style: AttuneTypography.soraBadge(color: isSelected ? colorScheme.primary : colorScheme.onSurface.withValues(alpha: 0.7))),
                      selected: isSelected,
                      selectedColor: colorScheme.primary.withValues(alpha: 0.22),
                      backgroundColor: Colors.white.withValues(alpha: 0.06),
                      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(18)),
                      side: BorderSide(color: isSelected ? colorScheme.primary.withValues(alpha: 0.5) : Colors.white12),
                      onSelected: (_) => setState(() => _selectedStyleOverride = style),
                    );
                  },
                ),
              ),

              const SizedBox(height: 20),

              // Featured Hero Mix Card (Shapey Material You 3 Hero)
              if (activeMix != null) ...[
                LiquidGlassContainer(
                  enableTilt: true,
                  padding: const EdgeInsets.all(18),
                  borderRadius: 28,
                  surfaceAlpha: 0.16,
                  onTap: () => _navigateToMixAlbum(context, activeMix),
                  child: Row(
                    children: [
                      Hero(
                        tag: 'mix_cover_${activeMix.id}',
                        child: AutogeneratedMixCover(
                          mix: activeMix,
                          size: 110,
                          borderRadius: 22,
                          styleOverride: _selectedStyleOverride,
                        ),
                      ),
                      const SizedBox(width: 16),
                      Expanded(
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            Container(
                              padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                              decoration: BoxDecoration(
                                color: colorScheme.primary.withValues(alpha: 0.2),
                                borderRadius: BorderRadius.circular(8),
                              ),
                              child: Text(
                                activeMix.badge,
                                style: AttuneTypography.soraBadge(
                                  color: colorScheme.primary,
                                  fontWeight: FontWeight.w700,
                                ),
                              ),
                            ),
                            const SizedBox(height: 6),
                            Text(
                              activeMix.title,
                              style: AttuneTypography.soraTitleMedium(
                                color: colorScheme.onSurface,
                                fontWeight: FontWeight.w700,
                              ),
                            ),
                            const SizedBox(height: 4),
                            Text(
                              activeMix.subtitle,
                              style: AttuneTypography.jakartaBodySmall(
                                color: colorScheme.onSurface.withValues(alpha: 0.7),
                              ),
                              maxLines: 2,
                              overflow: TextOverflow.ellipsis,
                            ),
                            const SizedBox(height: 12),
                            Row(
                              children: [
                                FilledButton.icon(
                                  style: FilledButton.styleFrom(
                                    backgroundColor: colorScheme.primary,
                                    foregroundColor: colorScheme.onPrimary,
                                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
                                    padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 8),
                                  ),
                                  icon: const Icon(Icons.play_arrow_rounded, size: 18),
                                  label: Text(
                                    context.tr('for_you_play_mix'),
                                    style: AttuneTypography.soraTitleSmall(color: colorScheme.onPrimary, fontSize: 13),
                                  ),
                                  onPressed: () => ForYouService.instance.playMix(
                                    activeMix,
                                    onOpenNowPlaying: widget.onOpenNowPlaying,
                                  ),
                                ),
                                const SizedBox(width: 8),
                                IconButton.filledTonal(
                                  icon: const Icon(Icons.album_rounded, size: 18),
                                  tooltip: 'Open Album View',
                                  onPressed: () => _navigateToMixAlbum(context, activeMix),
                                ),
                              ],
                            ),
                          ],
                        ),
                      ),
                    ],
                  ),
                ),
              ],

              const SizedBox(height: 24),

              // Algorithmic Mixes Grid
              Text(
                'YOUR ALGORITHMIC VIBES',
                style: AttuneTypography.soraSectionHeader(
                  color: colorScheme.primary,
                  fontWeight: FontWeight.w700,
                ),
              ),
              const SizedBox(height: 12),

              GridView.builder(
                shrinkWrap: true,
                physics: const NeverScrollableScrollPhysics(),
                gridDelegate: const SliverGridDelegateWithMaxCrossAxisExtent(
                  maxCrossAxisExtent: 190,
                  mainAxisSpacing: 16,
                  crossAxisSpacing: 16,
                  childAspectRatio: 0.74,
                ),
                itemCount: mixes.length,
                itemBuilder: (context, index) {
                  final mix = mixes[index];
                  return LiquidGlassContainer(
                    enableTilt: true,
                    borderRadius: 24,
                    padding: const EdgeInsets.all(12),
                    surfaceAlpha: 0.12,
                    onTap: () => _navigateToMixAlbum(context, mix),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Center(
                          child: Hero(
                            tag: 'mix_cover_${mix.id}',
                            child: AutogeneratedMixCover(
                              mix: mix,
                              size: 130,
                              borderRadius: 18,
                              styleOverride: _selectedStyleOverride,
                            ),
                          ),
                        ),
                        const SizedBox(height: 10),
                        Text(
                          mix.title,
                          style: AttuneTypography.soraTitleSmall(
                            color: colorScheme.onSurface,
                            fontSize: 13,
                          ),
                          maxLines: 1,
                          overflow: TextOverflow.ellipsis,
                        ),
                        const SizedBox(height: 2),
                        Text(
                          context.tr('for_you_mix_tracks', {'count': '${mix.tracks.length}'}),
                          style: AttuneTypography.jakartaBodySmall(
                            color: colorScheme.onSurface.withValues(alpha: 0.5),
                            fontSize: 11,
                          ),
                        ),
                      ],
                    ),
                  );
                },
              ),
            ],

            const SizedBox(height: 40),
          ],
        );
      },
    );
  }

  Widget _buildDesignTab({
    required String label,
    required bool isSelected,
    required VoidCallback onTap,
    required ColorScheme colorScheme,
  }) {
    return GestureDetector(
      onTap: onTap,
      behavior: HitTestBehavior.opaque,
      child: AnimatedContainer(
        duration: const Duration(milliseconds: 200),
        padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 6),
        decoration: BoxDecoration(
          color: isSelected ? colorScheme.primary.withValues(alpha: 0.25) : Colors.transparent,
          borderRadius: BorderRadius.circular(18),
        ),
        child: Text(
          label,
          style: AttuneTypography.soraBadge(
            color: isSelected ? colorScheme.primary : colorScheme.onSurface.withValues(alpha: 0.6),
            fontWeight: isSelected ? FontWeight.w700 : FontWeight.w500,
          ),
        ),
      ),
    );
  }
}
