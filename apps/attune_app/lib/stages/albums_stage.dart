                  _activeCollectionTabIndex == 0
                      ? '${albumNames.length} albums'
                      : '${mixes.length} algorithmic mixes',
                  style: AttuneTypography.soraBadge(
                    color: colorScheme.onSurface.withValues(alpha: 0.4),
                  ),
                ),
              ],
            ),

            const SizedBox(height: 14),

