                _buildTabFilterChip(
                  label: 'Algorithmic Mixes (${mixes.length})',
                  isSelected: _activeCollectionTabIndex == 1,
                  onTap: () => setState(() => _activeCollectionTabIndex = 1),
                  colorScheme: colorScheme,
                ),
              ],
            ),

            const SizedBox(height: 18),

            if (_activeCollectionTabIndex == 0) ...[
              // On-Repeat Flow Hero Banner Card (if tracks exist)
              if (onRepeatTracks.isNotEmpty) ...[
                _buildOnRepeatBannerCard(
                  tracks: onRepeatTracks,
                  colorScheme: colorScheme,
                  onTap: () {
                    final onRepeatMix = ForYouMix(
                      id: 'on_repeat_flow',
                      title: 'On-Repeat Flow',
                      subtitle: '${onRepeatTracks.length} tracks on heavy rotation',
                      vibeCategory: 'Heavy Rotation',
                      tracks: onRepeatTracks,
                      artStyle: ForYouArtStyle.geometricPulse,
                      badge: 'ON REPEAT',
                      primaryColor: colorScheme.primary,
                      secondaryColor: colorScheme.tertiary,
                    );
                    Navigator.of(context).push(
                      MaterialPageRoute(
                        builder: (_) => AutogenMixStage(
                          mix: onRepeatMix,
                          onOpenNowPlaying: widget.onOpenNowPlaying,
                        ),
                      ),
                    );
                  },
                  onPlay: () {
                    controller.playTrack(onRepeatTracks.first);
                    widget.onOpenNowPlaying?.call();
                  },
                ),
                const SizedBox(height: 20),
              ],

              // Grid of Albums
              GridView.builder(
                shrinkWrap: true,
                physics: const NeverScrollableScrollPhysics(),
                gridDelegate: const SliverGridDelegateWithMaxCrossAxisExtent(
                  maxCrossAxisExtent: 220,
                  mainAxisSpacing: 16,
                  crossAxisSpacing: 16,
                  childAspectRatio: 0.76,
                ),
                itemCount: albumNames.length,
                itemBuilder: (context, index) {
                  final name = albumNames[index];
                  final tracks = albumMap[name]!;
                  final customSplash = _customAlbumMetadata[name]?.customSplashArt;
                  final firstWithArtwork = tracks.firstWhere(
                    (t) => t.artworkFile != null && File(t.artworkFile!).existsSync(),
                    orElse: () => tracks.first,
                  );

                  return _buildAlbumCard(
                    name: name,
                    tracks: tracks,
                    leadTrack: firstWithArtwork,
                    customSplashArt: customSplash,
                    colorScheme: colorScheme,
                    onTap: () => setState(() => _selectedAlbum = name),
                  );
                },
              ),
            ] else ...[
              _buildAlgorithmicMixesView(
                mixes: mixes,
                colorScheme: colorScheme,
                controller: controller,
              ),
            ],

            const SizedBox(height: 90),
          ],
        );
      },
    );
  }

