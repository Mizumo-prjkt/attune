/// AlbumsStage: Replaces lyrics in main navigation with a dedicated Album library.
/// Overhauled with:
/// - Top immersive hero artwork banner with prominent title overlay
/// - Floating Liquid Glass card overlapping the artwork
/// - Google M3 style split pill button ([ ▶ Play Album | ▾ ])
/// - Rich album liner notes / description (e.g. Ai Kotoba lore & autogenerated mix rationale)
/// - Editable track values (Title, Artist, BPM, Key, Genre)
/// - Add / remove songs to and from albums
/// - Dynamic "On-Repeat Flow & Heavy Rotation" playlist
class AlbumsStage extends StatefulWidget {
  final VoidCallback? onOpenNowPlaying;
  final String? initialSelectedAlbum;

  const AlbumsStage({
    super.key,
    this.onOpenNowPlaying,
    this.initialSelectedAlbum,
  });

  @override
  State<AlbumsStage> createState() => _AlbumsStageState();
}

class _AlbumsStageState extends State<AlbumsStage> {
  String? _selectedAlbum;
  final Map<String, String> _customDescriptions = {};

  @override
  void initState() {
    super.initState();
    _selectedAlbum = widget.initialSelectedAlbum;
    _loadCustomDescriptions();
  }

  File get _descriptionsFile {
    final dir = AppEnvironmentDelegator.current.appDataDirectory;
    return File('${dir.path}/album_descriptions.json');
  }

  void _loadCustomDescriptions() {
    try {
      final f = _descriptionsFile;
      if (f.existsSync()) {
        final content = f.readAsStringSync();
        if (content.isNotEmpty) {
          final map = jsonDecode(content) as Map<String, dynamic>;
          _customDescriptions.addAll(map.map((k, v) => MapEntry(k, v.toString())));
        }
      }
    } catch (_) {}
  }

  void _saveCustomDescriptions() {
    try {
      final f = _descriptionsFile;
      f.writeAsStringSync(jsonEncode(_customDescriptions));
    } catch (_) {}
  }

  /// Dynamically computes liner notes & profile summary from genuine track metadata
  /// Zero hardcoded album titles or lore strings.
  String _getAlbumDescription(String albumName, List<TrackItem> tracks) {
    if (_customDescriptions.containsKey(albumName) && _customDescriptions[albumName]!.trim().isNotEmpty) {
      return _customDescriptions[albumName]!;
    }

    if (tracks.isEmpty) {
      return 'No audio metadata or profile notes recorded yet for this collection.';
    }

    final isAlgorithmic = albumName.toLowerCase().contains('flow') || albumName.toLowerCase().contains('mix');
    final artists = tracks.map((t) => t.artist).where((a) => a.isNotEmpty).toSet().toList();
    final bpms = tracks.where((t) => t.hasBpm && t.bpm > 0).map((t) => t.bpm).toList();
    final keys = tracks.where((t) => t.musicalKey != 'Pending Profile').map((t) => t.musicalKey).toSet().toList();
    final formats = tracks.map((t) => t.format).toSet().toList();
    final losslessCount = tracks.where((t) => t.isLossless).length;

    final bpmSummary = bpms.isNotEmpty
        ? 'Tempos range from ${bpms.reduce(math.min).toInt()} to ${bpms.reduce(math.max).toInt()} BPM.'
        : 'Tempo profiling pending audio transition scan.';

    final harmonicSummary = keys.isNotEmpty
        ? 'Root key signatures include ${keys.take(3).join(', ')}.'
        : 'Harmonic chroma pending CQT analysis.';

    final formatSummary = losslessCount > 0
        ? '$losslessCount lossless tracks (${formats.join('/')}).'
        : '${formats.join('/')} standard audio.';

    if (isAlgorithmic) {
      final artistList = artists.isNotEmpty ? ' across ${artists.take(3).join(', ')}' : '';
      return 'Algorithmic curation crafted dynamically from ${tracks.length} tracks$artistList. $bpmSummary $harmonicSummary Optimized for seamless Hermite-interpolated transitions and harmonic compatibility.';
    }

    final artistStr = artists.length == 1
        ? 'by ${artists.first}'
        : (artists.isNotEmpty ? 'featuring ${artists.take(3).join(', ')}${artists.length > 3 ? ' and others' : ''}' : '');

    return 'Collection of ${tracks.length} tracks $artistStr. $formatSummary $bpmSummary $harmonicSummary Notes and background lore can be edited or fetched dynamically.';
  }

  @override
  Widget build(BuildContext context) {
    final colorScheme = Theme.of(context).colorScheme;

    return ListenableBuilder(
      listenable: PlaybackController.instance,
      builder: (context, _) {
        final controller = PlaybackController.instance;
        final allTracks = controller.libraryTracks;
        final onRepeatTracks = controller.getRepeatHookTracks(limit: 12);

        // Group tracks by album name
        final albumMap = <String, List<TrackItem>>{};
        for (final track in allTracks) {
          final albumName = track.album.isNotEmpty ? track.album : 'Singles & Loose Tracks';
          albumMap.putIfAbsent(albumName, () => []).add(track);
        }

        // Include On-Repeat Flow as a dynamic collection if available
        if (onRepeatTracks.isNotEmpty) {
          albumMap['On-Repeat Flow'] = onRepeatTracks;
        }

        final albumNames = albumMap.keys.toList()
          ..sort((a, b) {
            if (a == 'On-Repeat Flow') return -1;
            if (b == 'On-Repeat Flow') return 1;
            return a.compareTo(b);
          });

        if (_selectedAlbum != null && albumMap.containsKey(_selectedAlbum)) {
          return _buildAlbumDetailView(
            albumName: _selectedAlbum!,
            tracks: albumMap[_selectedAlbum!]!,
            colorScheme: colorScheme,
            controller: controller,
          );
        }

        return ListView(
          physics: const BouncingScrollPhysics(),
          padding: const EdgeInsets.symmetric(horizontal: 20.0, vertical: 16.0),
          children: [
            // Header
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Text(
                  'ALBUMS & COLLECTIONS',
                  style: AttuneTypography.soraBadge(
                    color: colorScheme.primary,
                    fontWeight: FontWeight.w700,
                  ),
                ),
                Text(
                  '${albumNames.length} collections',
                  style: AttuneTypography.soraBadge(
                    color: colorScheme.onSurface.withValues(alpha: 0.4),
                  ),
                ),
              ],
            ),

            const SizedBox(height: 16),

            // On-Repeat Flow Hero Banner Card (if tracks exist)
            if (onRepeatTracks.isNotEmpty) ...[
              _buildOnRepeatBannerCard(
                tracks: onRepeatTracks,
                colorScheme: colorScheme,
                onTap: () => setState(() => _selectedAlbum = 'On-Repeat Flow'),
                onPlay: () {
                  controller.playTrack(onRepeatTracks.first);
                  widget.onOpenNowPlaying?.call();
                },
              ),
              const SizedBox(height: 20),
            ],

            // Grid of Albums
            GridView.builder(
              shrinkWrap: true,
              physics: const NeverScrollableScrollPhysics(),
              gridDelegate: const SliverGridDelegateWithMaxCrossAxisExtent(
                maxCrossAxisExtent: 220,
                mainAxisSpacing: 16,
                crossAxisSpacing: 16,
                childAspectRatio: 0.76,
              ),
              itemCount: albumNames.length,
              itemBuilder: (context, index) {
                final name = albumNames[index];
                final tracks = albumMap[name]!;
                final firstWithArtwork = tracks.firstWhere(
                  (t) => t.artworkFile != null && File(t.artworkFile!).existsSync(),
                  orElse: () => tracks.first,
                );

                return _buildAlbumCard(
                  name: name,
                  tracks: tracks,
                  leadTrack: firstWithArtwork,
                  isAlgorithmicMix: name == 'On-Repeat Flow',
                  colorScheme: colorScheme,
                  onTap: () => setState(() => _selectedAlbum = name),
                );
              },
            ),

            const SizedBox(height: 90),
          ],
        );
      },
    );
  }

