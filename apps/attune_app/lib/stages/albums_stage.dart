                              shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(14)),
                            ),
                            onPressed: () {
                              final newBpm = double.tryParse(bpmController.text.trim()) ?? track.bpm;
                              controller.updateTrackMetadata(
                                trackId: track.id,
                                title: titleController.text.trim().isNotEmpty ? titleController.text.trim() : null,
                                artist: artistController.text.trim().isNotEmpty ? artistController.text.trim() : null,
                                bpm: newBpm > 0 ? newBpm : null,
                                musicalKey: keyController.text.trim().isNotEmpty ? keyController.text.trim() : null,
                                genre: genreController.text.trim().isNotEmpty ? genreController.text.trim() : null,
                              );
                              Navigator.of(context).pop();
                            },
                            child: const Text('Save Values'),
                          ),
                        ],
                      ),
