/// Structured custom metadata for albums (Year, Genre, Splash Art, Lore/Description)
class AlbumCustomMetadata {
  final String? year;
  final String? genre;
  final String? customSplashArt;
  final String? description;

  const AlbumCustomMetadata({
    this.year,
    this.genre,
    this.customSplashArt,
    this.description,
  });

  Map<String, dynamic> toJson() => {
    if (year != null && year!.isNotEmpty) 'year': year,
    if (genre != null && genre!.isNotEmpty) 'genre': genre,
    if (customSplashArt != null && customSplashArt!.isNotEmpty) 'customSplashArt': customSplashArt,
    if (description != null && description!.isNotEmpty) 'description': description,
  };

  factory AlbumCustomMetadata.fromJson(dynamic json) {
    if (json is String) {
      return AlbumCustomMetadata(description: json);
    }
    if (json is Map) {
      return AlbumCustomMetadata(
        year: json['year']?.toString(),
        genre: json['genre']?.toString(),
        customSplashArt: json['customSplashArt']?.toString(),
        description: json['description']?.toString(),
      );
    }
    return const AlbumCustomMetadata();
  }
}

/// AlbumsStage: Main library navigation for user Albums and Algorithmic Mixes.
/// Features:
/// - Top immersive hero artwork banner with prominent title overlay & custom splash art
/// - Overlapping Liquid Glass card with Year, Genre, Track Count, Duration & M3 Split Pill Button
/// - Tab switching between "All Albums" and "Algorithmic Mixes"
/// - Dedicated AutogenMixStage navigation for autogenerated playlists with dynamic vector artwork
/// - Album metadata editor: Year, Genre, Splash Art (with quick track artwork picker), and Lore
/// - Track value editor: Song Title, File Name, Artist, Genre with read-only DSP Acoustic Profile
/// - Add / remove tracks to and from albums
class AlbumsStage extends StatefulWidget {
  final VoidCallback? onOpenNowPlaying;
  final String? initialSelectedAlbum;

  const AlbumsStage({
    super.key,
    this.onOpenNowPlaying,
    this.initialSelectedAlbum,
  });

  @override
  State<AlbumsStage> createState() => _AlbumsStageState();
}

class _AlbumsStageState extends State<AlbumsStage> {
  String? _selectedAlbum;
  int _activeCollectionTabIndex = 0; // 0: User Albums, 1: Algorithmic Mixes
  final Map<String, AlbumCustomMetadata> _customAlbumMetadata = {};

  @override
  void initState() {
    super.initState();
    _selectedAlbum = widget.initialSelectedAlbum;
    _loadCustomMetadata();
  }

  File get _metadataFile {
    final dir = AppEnvironmentDelegator.current.appDataDirectory;
    return File('${dir.path}/album_metadata.json');
  }

  File get _descriptionsFile {
    final dir = AppEnvironmentDelegator.current.appDataDirectory;
    return File('${dir.path}/album_descriptions.json');
  }

  void _loadCustomMetadata() {
    try {
      final metaFile = _metadataFile;
      if (metaFile.existsSync()) {
        final content = metaFile.readAsStringSync();
        if (content.isNotEmpty) {
          final map = jsonDecode(content) as Map<String, dynamic>;
          map.forEach((k, v) {
            _customAlbumMetadata[k] = AlbumCustomMetadata.fromJson(v);
          });
          return;
        }
      }

      // Legacy fallback
      final f = _descriptionsFile;
      if (f.existsSync()) {
        final content = f.readAsStringSync();
        if (content.isNotEmpty) {
          final map = jsonDecode(content) as Map<String, dynamic>;
          map.forEach((k, v) {
            _customAlbumMetadata[k] = AlbumCustomMetadata(description: v.toString());
          });
        }
      }
    } catch (_) {}
  }

  void _saveCustomMetadata() {
    try {
      final metaFile = _metadataFile;
      final jsonMap = _customAlbumMetadata.map((k, v) => MapEntry(k, v.toJson()));
      metaFile.writeAsStringSync(jsonEncode(jsonMap));

      // Also sync legacy descriptions file
      final descFile = _descriptionsFile;
      final descMap = _customAlbumMetadata.map((k, v) => MapEntry(k, v.description ?? ''));
      descFile.writeAsStringSync(jsonEncode(descMap));
    } catch (_) {}
  }

  /// Dynamically computes liner notes & profile summary from genuine track metadata.
  /// Zero hardcoded album titles or lore strings.
  String _getAlbumDescription(String albumName, List<TrackItem> tracks) {
    final customDesc = _customAlbumMetadata[albumName]?.description;
    if (customDesc != null && customDesc.trim().isNotEmpty) {
      return customDesc;
    }

    if (tracks.isEmpty) {
      return 'No audio metadata or profile notes recorded yet for this collection.';
    }

    final isAlgorithmic = albumName.toLowerCase().contains('flow') || albumName.toLowerCase().contains('mix');
    final artists = tracks.map((t) => t.artist).where((a) => a.isNotEmpty).toSet().toList();
    final bpms = tracks.where((t) => t.hasBpm && t.bpm > 0).map((t) => t.bpm).toList();
    final keys = tracks.where((t) => t.musicalKey != 'Pending Profile').map((t) => t.musicalKey).toSet().toList();
    final formats = tracks.map((t) => t.format).toSet().toList();
    final losslessCount = tracks.where((t) => t.isLossless).length;

    final bpmSummary = bpms.isNotEmpty
        ? 'Tempos range from ${bpms.reduce(math.min).toInt()} to ${bpms.reduce(math.max).toInt()} BPM.'
        : 'Tempo profiling pending audio transition scan.';

    final harmonicSummary = keys.isNotEmpty
        ? 'Root key signatures include ${keys.take(3).join(', ')}.'
        : 'Harmonic chroma pending CQT analysis.';

    final formatSummary = losslessCount > 0
        ? '$losslessCount lossless tracks (${formats.join('/')}).'
        : '${formats.join('/')} standard audio.';

    if (isAlgorithmic) {
      final artistList = artists.isNotEmpty ? ' across ${artists.take(3).join(', ')}' : '';
      return 'Algorithmic curation crafted dynamically from ${tracks.length} tracks$artistList. $bpmSummary $harmonicSummary Optimized for seamless Hermite-interpolated transitions and harmonic compatibility.';
    }

    final artistStr = artists.length == 1
        ? 'by ${artists.first}'
        : (artists.isNotEmpty ? 'featuring ${artists.take(3).join(', ')}${artists.length > 3 ? ' and others' : ''}' : '');

    return 'Collection of ${tracks.length} tracks $artistStr. $formatSummary $bpmSummary $harmonicSummary Notes and background lore can be edited or fetched dynamically.';
  }

