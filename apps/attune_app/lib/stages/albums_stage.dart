            isDense: true,
            filled: true,
            fillColor: Colors.white.withValues(alpha: 0.08),
            contentPadding: const EdgeInsets.symmetric(horizontal: 12, vertical: 10),
            border: OutlineInputBorder(
              borderRadius: BorderRadius.circular(12),
              borderSide: BorderSide.none,
            ),
          ),
        ),
      ],
    );
  }

  /// Dialog to add songs from the general library into this album
  void _showAddSongDialog(
    String albumName,
    List<TrackItem> currentTracks,
    PlaybackController controller,
  ) {
    final currentIds = currentTracks.map((t) => t.id).toSet();
    final availableTracks = controller.libraryTracks.where((t) => !currentIds.contains(t.id)).toList();

    showDialog(
      context: context,
      barrierColor: Colors.black.withValues(alpha: 0.5),
      builder: (context) {
        final colorScheme = Theme.of(context).colorScheme;
        return Center(
          child: ConstrainedBox(
            constraints: const BoxConstraints(maxWidth: 440, maxHeight: 520),
            child: LiquidGlassContainer(
              margin: const EdgeInsets.symmetric(horizontal: 20),
              padding: const EdgeInsets.all(22),
              borderRadius: 24,
              surfaceAlpha: 0.24,
              blurSigma: 32,
              child: Material(
                color: Colors.transparent,
                child: Column(
                  mainAxisSize: MainAxisSize.min,
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      mainAxisAlignment: MainAxisAlignment.spaceBetween,
                      children: [
                        Text(
                          'Add Song to Album',
                          style: AttuneTypography.soraHeading(
                            fontSize: 18,
                            fontWeight: FontWeight.w700,
                            color: colorScheme.onSurface,
                          ),
                        ),
                        IconButton(
                          icon: const Icon(Icons.close_rounded, size: 20),
                          color: colorScheme.onSurface.withValues(alpha: 0.6),
                          onPressed: () => Navigator.of(context).pop(),
                        ),
                      ],
                    ),
                    const SizedBox(height: 4),
                    Text(
                      'Choose a track from your library to add into "$albumName"',
                      style: AttuneTypography.jakartaBodySmall(
                        color: colorScheme.onSurface.withValues(alpha: 0.6),
                      ),
                    ),
                    const SizedBox(height: 14),

                    Expanded(
                      child: availableTracks.isEmpty
                          ? Center(
                              child: Text(
                                'All library tracks are already in this album',
                                style: AttuneTypography.jakartaBody(
                                  color: colorScheme.onSurface.withValues(alpha: 0.5),
                                ),
                              ),
                            )
                          : ListView.builder(
                              physics: const BouncingScrollPhysics(),
                              itemCount: availableTracks.length,
                              itemBuilder: (context, index) {
                                final track = availableTracks[index];
                                return ListTile(
                                  contentPadding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                                  title: Text(
                                    track.title,
                                    maxLines: 1,
                                    overflow: TextOverflow.ellipsis,
                                    style: AttuneTypography.soraSubheading(
                                      fontSize: 13.5,
                                      color: colorScheme.onSurface,
                                    ),
                                  ),
                                  subtitle: Text(
                                    '${track.artist} • ${track.album}',
                                    maxLines: 1,
                                    overflow: TextOverflow.ellipsis,
                                    style: AttuneTypography.jakartaBodySmall(
                                      color: colorScheme.onSurface.withValues(alpha: 0.5),
                                    ),
                                  ),
                                  trailing: IconButton(
                                    icon: Icon(Icons.add_circle_outline_rounded, color: colorScheme.primary),
                                    onPressed: () {
                                      controller.addTrackToAlbum(trackId: track.id, albumName: albumName);
                                      Navigator.of(context).pop();
                                    },
                                  ),
                                );
                              },
                            ),
                    ),
                  ],
                ),
              ),
            ),
          ),
        );
      },
    );
  }
