  Widget _buildAlbumDetailView({
    required String albumName,
    required List<TrackItem> tracks,
    required ColorScheme colorScheme,
    required PlaybackController controller,
  }) {
    final firstTrack = tracks.first;
    final customMetadata = _customAlbumMetadata[albumName];
    final hasCustomSplash = customMetadata?.customSplashArt != null &&
        customMetadata!.customSplashArt!.isNotEmpty &&
        File(customMetadata.customSplashArt!).existsSync();
    final hasArtwork = firstTrack.artworkFile != null && File(firstTrack.artworkFile!).existsSync();
    final isAlgorithmic = albumName == 'On-Repeat Flow' || albumName.contains('Mix');
    final description = _getAlbumDescription(albumName, tracks);

    final totalSeconds = tracks.fold<int>(0, (sum, t) => sum + t.duration.inSeconds);
    final durationStr = totalSeconds >= 3600
        ? '${totalSeconds ~/ 3600} hr ${(totalSeconds % 3600) ~/ 60} min'
        : '${totalSeconds ~/ 60} min ${totalSeconds % 60} sec';

    final metaParts = <String>[];
    if (customMetadata?.year != null && customMetadata!.year!.isNotEmpty) {
      metaParts.add(customMetadata.year!);
    }
    if (customMetadata?.genre != null && customMetadata!.genre!.isNotEmpty) {
      metaParts.add(customMetadata.genre!);
    }
    metaParts.add('${tracks.length} songs');
    metaParts.add(durationStr);
    final metaSubline = metaParts.join(' • ');

    return ListView(
      physics: const BouncingScrollPhysics(),
      padding: EdgeInsets.zero,
      children: [
        // 1. Immersive Top Hero Artwork Banner with Overlay (Section 1)
        Stack(
          children: [
            // Top Artwork Banner
            Container(
              height: 290,
              width: double.infinity,
              decoration: BoxDecoration(
                color: Colors.black,
                gradient: LinearGradient(
                  colors: [
                    firstTrack.seedColor.withValues(alpha: 0.8),
                    colorScheme.surface,
                  ],
                  begin: Alignment.topCenter,
                  end: Alignment.bottomCenter,
                ),
              ),
              child: Stack(
                fit: StackFit.expand,
                children: [
                  if (hasCustomSplash)
                    Image.file(
                      File(customMetadata.customSplashArt!),
                      fit: BoxFit.cover,
                    )
                  else if (hasArtwork && !isAlgorithmic)
                    Image.file(
                      File(firstTrack.artworkFile!),
                      fit: BoxFit.cover,
                    )
                  else
                    Container(
                      decoration: BoxDecoration(
                        gradient: LinearGradient(
                          colors: [firstTrack.seedColor, colorScheme.primaryContainer],
                          begin: Alignment.topLeft,
                          end: Alignment.bottomRight,
                        ),
                      ),
                      child: Center(
                        child: Icon(
                          isAlgorithmic ? Icons.auto_awesome_rounded : Icons.album_rounded,
                          size: 96,
                          color: Colors.white.withValues(alpha: 0.4),
                        ),
                      ),
                    ),
                  // Dark Vignette Gradient Overlay
                  Container(
                    decoration: BoxDecoration(
                      gradient: LinearGradient(
                        colors: [
                          Colors.black.withValues(alpha: 0.35),
                          Colors.black.withValues(alpha: 0.75),
                          colorScheme.surface,
                        ],
                        begin: Alignment.topCenter,
                        end: Alignment.bottomCenter,
                      ),
                    ),
                  ),
                ],
              ),
            ),

            // Back Button Pill (Top Left)
            Positioned(
              top: 48,
              left: 20,
              child: GestureDetector(
                onTap: () {
                  if (widget.initialSelectedAlbum != null && Navigator.canPop(context)) {
                    Navigator.of(context).pop();
                  } else {
                    setState(() => _selectedAlbum = null);
                  }
                },
