  void _handleAlbumMenuAction(
    String action,
    String albumName,
    List<TrackItem> tracks,
    PlaybackController controller,
  ) {
    switch (action) {
      case 'shuffle':
        if (tracks.isNotEmpty) {
          final shuffled = List<TrackItem>.from(tracks)..shuffle();
          controller.playTrack(shuffled.first);
          widget.onOpenNowPlaying?.call();
        }
        break;
      case 'add_songs':
        _showAddSongDialog(albumName, tracks, controller);
        break;
      case 'edit_notes':
        _showEditDescriptionDialog(albumName, _getAlbumDescription(albumName, tracks));
        break;
    }
  }

  /// Floating Liquid Glass Dialog to edit track values (Title, Artist, BPM, Key, Genre)
  void _showEditTrackValuesDialog(TrackItem track, PlaybackController controller) {
    final titleController = TextEditingController(text: track.title);
    final artistController = TextEditingController(text: track.artist);
    final bpmController = TextEditingController(text: track.hasBpm ? track.bpm.toStringAsFixed(1) : '');
    final keyController = TextEditingController(text: track.musicalKey != 'Pending Profile' ? track.musicalKey : '');
    final genreController = TextEditingController(text: track.genre);

    showDialog(
      context: context,
      barrierColor: Colors.black.withValues(alpha: 0.5),
      builder: (context) {
        final colorScheme = Theme.of(context).colorScheme;
        return Center(
          child: ConstrainedBox(
            constraints: const BoxConstraints(maxWidth: 420),
            child: LiquidGlassContainer(
              margin: const EdgeInsets.symmetric(horizontal: 20),
              padding: const EdgeInsets.all(22),
              borderRadius: 24,
              surfaceAlpha: 0.24,
              blurSigma: 32,
              child: Material(
                color: Colors.transparent,
                child: SingleChildScrollView(
                  child: Column(
                    mainAxisSize: MainAxisSize.min,
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Row(
                        mainAxisAlignment: MainAxisAlignment.spaceBetween,
                        children: [
                          Text(
                            'Edit Track Values',
                            style: AttuneTypography.soraHeading(
                              fontSize: 18,
                              fontWeight: FontWeight.w700,
                              color: colorScheme.onSurface,
                            ),
                          ),
                          IconButton(
                            icon: const Icon(Icons.close_rounded, size: 20),
                            color: colorScheme.onSurface.withValues(alpha: 0.6),
                            onPressed: () => Navigator.of(context).pop(),
                          ),
                        ],
                      ),
                      const SizedBox(height: 14),

                      _buildTextField('Song Title', titleController, colorScheme),
                      const SizedBox(height: 10),
                      _buildTextField('Artist', artistController, colorScheme),
                      const SizedBox(height: 10),
                      Row(
                        children: [
                          Expanded(child: _buildTextField('BPM', bpmController, colorScheme, isNumber: true)),
                          const SizedBox(width: 12),
                          Expanded(child: _buildTextField('Key (e.g. C Major)', keyController, colorScheme)),
                        ],
                      ),
                      const SizedBox(height: 10),
                      _buildTextField('Genre (e.g. Rock, Pop, Synth)', genreController, colorScheme),

                      const SizedBox(height: 20),

                      Row(
                        mainAxisAlignment: MainAxisAlignment.end,
                        children: [
                          TextButton(
                            onPressed: () => Navigator.of(context).pop(),
                            child: Text('Cancel', style: TextStyle(color: colorScheme.onSurface.withValues(alpha: 0.7))),
