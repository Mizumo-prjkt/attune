                            _buildFilterChip('For You Mixes', BubbleFilterMode.forYouMixes),
                            _buildFilterChip('Rock', BubbleFilterMode.rock),
                            _buildFilterChip('Pop', BubbleFilterMode.pop),
                            _buildFilterChip('Electronic', BubbleFilterMode.electronic),
                          ],
                        ),
                      ),
                    ],
                  ),
                ),

                // 3. Center Target Catch Reticle (Subtle Spherical Lens Cue)
                Positioned(
                  left: centerX - 54,
                  top: centerY - 54,
                  width: 108,
                  height: 108,
                  child: IgnorePointer(
                    child: Container(
                      decoration: BoxDecoration(
                        shape: BoxShape.circle,
                        border: Border.all(
                          color: colorScheme.primary.withValues(alpha: 0.26),
                          width: 1.2,
                        ),
                      ),
                    ),
                  ),
                ),

                // 3.5 Bottom Gradient Scrim to ensure the floating card pops out with high contrast
                Positioned(
                  bottom: 0,
                  left: 0,
                  right: 0,
                  height: 190,
                  child: IgnorePointer(
                    child: Container(
                      decoration: BoxDecoration(
                        gradient: LinearGradient(
                          begin: Alignment.topCenter,
                          end: Alignment.bottomCenter,
                          colors: [
                            Colors.transparent,
                            Colors.black.withValues(alpha: 0.60),
                            Colors.black.withValues(alpha: 0.92),
                          ],
                        ),
                      ),
                    ),
                  ),
                ),

                // 4. Bottom Floating Liquid Glass Highlight Card
                if (highlightedItem != null)
                  Positioned(
                    bottom: 20,
                    left: 16,
                    right: 16,
                    child: Center(
