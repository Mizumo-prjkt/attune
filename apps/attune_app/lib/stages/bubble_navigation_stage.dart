                          surfaceAlpha: 0.95,
                          tintOverride: const Color(0xF4121722),
                          borderColor: colorScheme.primary.withValues(alpha: 0.40),
                          boxShadow: [
                            BoxShadow(
                              color: Colors.black.withValues(alpha: 0.85),
                              blurRadius: 32,
                              spreadRadius: 4,
                              offset: const Offset(0, 8),
                            ),
