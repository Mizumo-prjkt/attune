/// Generic bubble item model for hexagonal honeycomb Bubblegrid navigation
class BubbleItem {
  final String id;
  final String title;
  final String subtitle;
  final String? album;
  final String? artworkFile;
  final String? artworkAsset;
  final bool hasArtworkFile;
  final Color seedColor;
  final double bpm;
  final String musicalKey;
  final TrackItem? track;
  final ForYouMix? mix;
  final List<TrackItem> albumTracks;
  final Offset baseOffset;

  const BubbleItem({
    required this.id,
    required this.title,
    required this.subtitle,
    this.album,
    this.artworkFile,
    this.artworkAsset,
    this.hasArtworkFile = false,
    required this.seedColor,
    this.bpm = 0.0,
    this.musicalKey = '--',
    this.track,
    this.mix,
    this.albumTracks = const [],
    this.baseOffset = Offset.zero,
  });

  BubbleItem copyWithPosition(Offset offset) {
    return BubbleItem(
      id: id,
      title: title,
      subtitle: subtitle,
      album: album,
      artworkFile: artworkFile,
      artworkAsset: artworkAsset,
      hasArtworkFile: hasArtworkFile,
      seedColor: seedColor,
      bpm: bpm,
      musicalKey: musicalKey,
      track: track,
      mix: mix,
      albumTracks: albumTracks,
      baseOffset: offset,
    );
  }
}

/// Filter mode for the Bubblegrid selection
enum BubbleFilterMode {
  allTracks,
  albums,
  forYouMixes,
  rock,
  pop,
  electronic,
}

/// Full-screen Bubblegrid Selection & Highlight Stage
class BubbleNavigationStage extends StatefulWidget {
  final VoidCallback? onOpenNowPlaying;
  final String? initialHighlightTrackId;

  const BubbleNavigationStage({
    super.key,
    this.onOpenNowPlaying,
    this.initialHighlightTrackId,
  });

  @override
  State<BubbleNavigationStage> createState() => _BubbleNavigationStageState();
}

class _BubbleNavigationStageState extends State<BubbleNavigationStage>
    with SingleTickerProviderStateMixin {
  BubbleFilterMode _filterMode = BubbleFilterMode.allTracks;

  // 2D Pan Offset relative to canvas origin
  Offset _panOffset = Offset.zero;

  // Momentum and Spring animation
  late final AnimationController _animController;
  Animation<Offset>? _panAnimation;

  // Highlighted item index
  int _highlightedIndex = 0;
  List<BubbleItem> _items = [];

  static const double _hexSpacing = 82.0;
  static const double _baseDiameter = 74.0;

  @override
  void initState() {
    super.initState();
    TiltService.instance.registerViewer();

    _animController = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 400),
    )..addListener(() {
        if (_panAnimation != null) {
          setState(() {
            _panOffset = _panAnimation!.value;
          });
        }
      });

    WidgetsBinding.instance.addPostFrameCallback((_) {
      _rebuildItems();
    });
  }

  @override
  void dispose() {
    TiltService.instance.unregisterViewer();
    _animController.dispose();
    super.dispose();
  }

  /// Calculates concentric hexagonal honeycomb positions for [count] items
  List<Offset> _generateHexagonalPositions(int count) {
    if (count <= 0) return [];
    final positions = <Offset>[Offset.zero]; // Center item at (0, 0)
    if (count == 1) return positions;

    int ring = 1;
    while (positions.length < count) {
      // 6 corners of regular hexagon at distance ring * spacing
      for (int side = 0; side < 6; side++) {
        final angle1 = side * (math.pi / 3.0);
        final angle2 = (side + 1) * (math.pi / 3.0);

        final corner1 = Offset(
          ring * _hexSpacing * math.cos(angle1),
          ring * _hexSpacing * math.sin(angle1),
        );
        final corner2 = Offset(
          ring * _hexSpacing * math.cos(angle2),
          ring * _hexSpacing * math.sin(angle2),
        );

        for (int step = 0; step < ring; step++) {
          final frac = step / ring.toDouble();
          final pos = Offset(
            corner1.dx + (corner2.dx - corner1.dx) * frac,
            corner1.dy + (corner2.dy - corner1.dy) * frac,
          );
          positions.add(pos);
          if (positions.length >= count) return positions;
        }
      }
      ring++;
    }
    return positions;
  }

  void _rebuildItems() {
    final controller = PlaybackController.instance;
    final allTracks = controller.libraryTracks;
    final mixes = ForYouService.instance.generateMixes(context, allTracks);

    List<BubbleItem> rawItems = [];

    switch (_filterMode) {
      case BubbleFilterMode.allTracks:
        rawItems = allTracks.map((t) {
          final hasArt = t.artworkFile != null &&
              t.artworkFile!.isNotEmpty &&
              File(t.artworkFile!).existsSync();
          return BubbleItem(
            id: t.id,
            title: t.title,
            subtitle: t.artist,
            album: t.album,
            artworkFile: t.artworkFile,
            artworkAsset: t.artworkAsset,
            hasArtworkFile: hasArt,
            seedColor: t.seedColor,
            bpm: t.effectiveBpm,
            musicalKey: t.musicalKey,
            track: t,
          );
        }).toList();
        break;

      case BubbleFilterMode.albums:
        final albumMap = <String, List<TrackItem>>{};
        for (final t in allTracks) {
          final albumName = t.album.isNotEmpty ? t.album : 'Singles';
          albumMap.putIfAbsent(albumName, () => []).add(t);
        }
        rawItems = albumMap.entries.map((e) {
          final first = e.value.first;
          final hasArt = first.artworkFile != null &&
              first.artworkFile!.isNotEmpty &&
              File(first.artworkFile!).existsSync();
          return BubbleItem(
            id: 'album_${e.key}',
            title: e.key,
            subtitle: '${e.value.length} songs • ${first.artist}',
            album: e.key,
            artworkFile: first.artworkFile,
            artworkAsset: first.artworkAsset,
            hasArtworkFile: hasArt,
            seedColor: first.seedColor,
            bpm: first.effectiveBpm,
            musicalKey: first.musicalKey,
            albumTracks: e.value,
          );
        }).toList();
        break;

      case BubbleFilterMode.forYouMixes:
        rawItems = mixes.map((m) {
          final firstArt = m.tracks.isNotEmpty ? m.tracks.first.artworkFile : null;
          final hasArt = firstArt != null &&
              firstArt.isNotEmpty &&
              File(firstArt).existsSync();
          return BubbleItem(
            id: m.id,
            title: m.title,
            subtitle: m.subtitle,
            artworkFile: firstArt,
            hasArtworkFile: hasArt,
            seedColor: m.primaryColor,
            mix: m,
            albumTracks: m.tracks,
          );
        }).toList();
        break;

      case BubbleFilterMode.rock:
      case BubbleFilterMode.pop:
      case BubbleFilterMode.electronic:
        final genreStr = _filterMode == BubbleFilterMode.rock
            ? 'Rock'
            : (_filterMode == BubbleFilterMode.pop ? 'Pop' : 'Electronic');
        final filtered = allTracks.where((t) => t.genre.toLowerCase().contains(genreStr.toLowerCase())).toList();
        rawItems = filtered.map((t) {
          final hasArt = t.artworkFile != null &&
              t.artworkFile!.isNotEmpty &&
              File(t.artworkFile!).existsSync();
          return BubbleItem(
            id: t.id,
            title: t.title,
            subtitle: t.artist,
            album: t.album,
            artworkFile: t.artworkFile,
            artworkAsset: t.artworkAsset,
            hasArtworkFile: hasArt,
            seedColor: t.seedColor,
            bpm: t.effectiveBpm,
            musicalKey: t.musicalKey,
            track: t,
          );
        }).toList();
        break;
    }

    if (rawItems.isEmpty && allTracks.isNotEmpty) {
      rawItems = allTracks.take(30).map((t) {
        final hasArt = t.artworkFile != null &&
            t.artworkFile!.isNotEmpty &&
            File(t.artworkFile!).existsSync();
        return BubbleItem(
          id: t.id,
          title: t.title,
          subtitle: t.artist,
          album: t.album,
          artworkFile: t.artworkFile,
          artworkAsset: t.artworkAsset,
          hasArtworkFile: hasArt,
          seedColor: t.seedColor,
          bpm: t.effectiveBpm,
          musicalKey: t.musicalKey,
          track: t,
        );
      }).toList();
    }

    final positions = _generateHexagonalPositions(rawItems.length);
    final positionedItems = <BubbleItem>[];
    for (int i = 0; i < rawItems.length; i++) {
      positionedItems.add(rawItems[i].copyWithPosition(positions[i]));
    }

    setState(() {
      _items = positionedItems;
      _highlightedIndex = 0;
      _panOffset = Offset.zero;
    });

    if (widget.initialHighlightTrackId != null) {
      final targetIdx = _items.indexWhere((it) => it.track?.id == widget.initialHighlightTrackId || it.id == widget.initialHighlightTrackId);
      if (targetIdx != -1) {
        _centerOnIndex(targetIdx, animated: false);
      }
    }
  }

  int _findClosestIndex(Offset offset) {
    if (_items.isEmpty) return 0;
    int bestIdx = 0;
    double minDistance = double.infinity;
    for (int i = 0; i < _items.length; i++) {
      final d = (offset + _items[i].baseOffset).distance;
      if (d < minDistance) {
        minDistance = d;
        bestIdx = i;
      }
    }
    return bestIdx;
  }

  void _animateToOffset(
    Offset targetOffset, {
    Duration duration = const Duration(milliseconds: 320),
    Curve curve = Curves.easeOutCubic,
    int? targetIndex,
  }) {
    _animController.stop();
    _animController.duration = duration;
    _panAnimation = Tween<Offset>(
      begin: _panOffset,
      end: targetOffset,
    ).animate(CurvedAnimation(
      parent: _animController,
      curve: curve,
    ));
    if (targetIndex != null) {
      _highlightedIndex = targetIndex;
    }
    _animController.forward(from: 0.0);
  }

  void _snapToClosest({Offset velocity = Offset.zero}) {
    if (_items.isEmpty) return;

    final hasVelocity = velocity.distanceSquared > 25000; // > ~158 px/sec
    final momentumDelta = hasVelocity
        ? Offset(velocity.dx * 0.22, velocity.dy * 0.22)
        : Offset.zero;

    final candidateOffset = _panOffset + momentumDelta;
    final bestIndex = _findClosestIndex(candidateOffset);
    final targetOffset = -_items[bestIndex].baseOffset;

    final duration = hasVelocity
        ? const Duration(milliseconds: 380)
        : const Duration(milliseconds: 260);

    _animateToOffset(
      targetOffset,
      duration: duration,
      curve: Curves.easeOutCubic,
      targetIndex: bestIndex,
    );
  }

  void _centerOnIndex(int index, {bool animated = true}) {
    if (index < 0 || index >= _items.length) return;
    final item = _items[index];
    final targetOffset = -item.baseOffset;

    if (!animated) {
      setState(() {
        _panOffset = targetOffset;
        _highlightedIndex = index;
      });
      return;
    }

    _animateToOffset(
      targetOffset,
      duration: const Duration(milliseconds: 340),
      curve: Curves.easeOutCubic,
      targetIndex: index,
    );
  }

  void _onPanStart(DragStartDetails details) {
    _animController.stop();
  }

  void _onPanUpdate(DragUpdateDetails details) {
    setState(() {
      _panOffset += details.delta;
    });
  }

  void _onPanEnd(DragEndDetails details) {
    _snapToClosest(velocity: details.velocity.pixelsPerSecond);
  }

  void _playItem(BubbleItem item) {
    final controller = PlaybackController.instance;
    if (item.track != null) {
      controller.playTrack(item.track!);
    } else if (item.albumTracks.isNotEmpty) {
      controller.playTrack(item.albumTracks.first);
    } else if (item.mix != null && item.mix!.tracks.isNotEmpty) {
      controller.playTrack(item.mix!.tracks.first);
    }
  }

  void _navigateToAlbum(String albumName) {
    Navigator.of(context).push(
      MaterialPageRoute(
        builder: (_) => Scaffold(
          backgroundColor: Colors.transparent,
          body: SafeArea(
            child: AlbumsStage(
              initialSelectedAlbum: albumName,
              onOpenNowPlaying: widget.onOpenNowPlaying,
            ),
          ),
        ),
      ),
    );
  }

  Widget _buildBubbleContent(BubbleItem item, double size) {
    if (item.hasArtworkFile && item.artworkFile != null) {
      return Image.file(
        File(item.artworkFile!),
        width: size,
        height: size,
        fit: BoxFit.cover,
        gaplessPlayback: true,
        cacheWidth: 160,
        cacheHeight: 160,
      );
    } else if (item.artworkAsset != null && item.artworkAsset!.isNotEmpty) {
      return Image.asset(
        item.artworkAsset!,
        width: size,
        height: size,
        fit: BoxFit.cover,
        gaplessPlayback: true,
        cacheWidth: 160,
        cacheHeight: 160,
      );
    } else if (item.mix != null) {
      return AutogeneratedMixCover(
        mix: item.mix!,
        size: size,
      );
    }

    // Cohesive fallback procedural gradient with music note icon
    return Container(
      width: size,
      height: size,
      decoration: BoxDecoration(
        gradient: LinearGradient(
          begin: Alignment.topLeft,
          end: Alignment.bottomRight,
          colors: [
            item.seedColor,
            item.seedColor.withValues(alpha: 0.5),
          ],
        ),
      ),
      child: Center(
        child: Icon(
          Icons.music_note_rounded,
          color: Colors.white.withValues(alpha: 0.9),
          size: size * 0.42,
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final colorScheme = Theme.of(context).colorScheme;
    final controller = PlaybackController.instance;

    return Scaffold(
      backgroundColor: const Color(0xFF0D0F14), // Pure deep space-black surface
      body: SafeArea(
        child: LayoutBuilder(
          builder: (context, constraints) {
            final w = constraints.maxWidth;
            final h = constraints.maxHeight;

            // Screen center point
            final centerX = w / 2.0;
            // Shift center slightly upward so bottom highlight card does not collide
            final centerY = h / 2.0 - 45.0;

            final lensRadius = math.max(300.0, math.min(w, h) * 0.60);

            // Find closest bubble to center
            int closestIndex = 0;
            double minCenterDist = double.infinity;

            final visibleBubbles = <_RenderBubble>[];

            const double sMax = 1.36; // Center magnification (diameter ≈ 100px)
            const double sMin = 0.64; // Perimeter edge scale (diameter ≈ 47px)
            const double deltaS = sMax - sMin; // 0.72
            final double kFactor = deltaS / (2.0 * math.pi); // ≈ 0.1146

            for (int i = 0; i < _items.length; i++) {
              final item = _items[i];
              final sx = item.baseOffset.dx + _panOffset.dx;
              final sy = item.baseOffset.dy + _panOffset.dy;

              final dist = math.sqrt(sx * sx + sy * sy);

              if (dist < minCenterDist) {
                minCenterDist = dist;
                closestIndex = i;
              }

              final u = dist / lensRadius;
              final double scale;
              final double rPrime;

              if (u <= 1.0) {
                // Smooth integral cosine lens expansion & compression
                scale = sMin + (deltaS * 0.5) * (1.0 + math.cos(math.pi * u));
                rPrime = lensRadius * (u + kFactor * math.sin(math.pi * u));
              } else {
                scale = (sMin - 0.08 * (u - 1.0)).clamp(0.48, sMin);
                rPrime = lensRadius * (1.0 + sMin * (u - 1.0));
              }

              final double finalX;
              final double finalY;
              if (dist > 0.001) {
                final push = rPrime / dist;
                finalX = centerX + sx * push;
                finalY = centerY + sy * push;
              } else {
                finalX = centerX;
                finalY = centerY;
              }

              final diameter = _baseDiameter * scale;

              // Viewport Culling: Skip bubbles that are fully offscreen
              if (finalX + diameter < -40 ||
                  finalX - diameter > w + 40 ||
                  finalY + diameter < -40 ||
                  finalY - diameter > h + 40) {
                continue;
              }

              visibleBubbles.add(_RenderBubble(
                index: i,
                item: item,
                x: finalX,
                y: finalY,
                diameter: diameter,
                distFromCenter: dist,
                scale: scale,
              ));
            }

            // Synchronously resolve current highlight index
            final activeHighlightIndex = _animController.isAnimating ? _highlightedIndex : closestIndex;
            _highlightedIndex = activeHighlightIndex;

            final highlightedItem = _items.isNotEmpty && activeHighlightIndex < _items.length
                ? _items[activeHighlightIndex]
                : null;

            final isCurrentPlaying = highlightedItem?.track != null &&
                controller.currentTrack?.id == highlightedItem!.track!.id &&
                controller.isPlaying;

            // Sort visible bubbles by distance descending so center bubble renders on top (highest Z-index)
            visibleBubbles.sort((a, b) => b.distFromCenter.compareTo(a.distFromCenter));

            return Stack(
              children: [
                // 1. Interactive 2D Honeycomb Canvas
                GestureDetector(
                  onPanStart: _onPanStart,
                  onPanUpdate: _onPanUpdate,
                  onPanEnd: _onPanEnd,
                  onPanCancel: () => _snapToClosest(),
                  behavior: HitTestBehavior.opaque,
                  child: Container(
                    width: w,
                    height: h,
                    color: Colors.transparent,
                    child: Stack(
                      children: visibleBubbles.map((rb) {
                        final isHighlighted = rb.index == activeHighlightIndex;
                        return Positioned(
                          key: ValueKey('bubble_${rb.index}_${rb.item.id}'),
                          left: rb.x - rb.diameter / 2.0,
                          top: rb.y - rb.diameter / 2.0,
                          width: rb.diameter,
                          height: rb.diameter,
                          child: GestureDetector(
                            onTap: () {
                              if (isHighlighted) {
                                _playItem(rb.item);
                              } else {
                                _centerOnIndex(rb.index);
                              }
                            },
                            onDoubleTap: () {
                              _playItem(rb.item);
                            },
                            child: Container(
                              decoration: BoxDecoration(
                                shape: BoxShape.circle,
                                boxShadow: isHighlighted
                                    ? [
                                        BoxShadow(
                                          color: colorScheme.primary.withValues(alpha: 0.55),
                                          blurRadius: 18,
                                          spreadRadius: 2,
                                          offset: const Offset(0, 4),
                                        ),
                                      ]
                                    : null,
                                border: Border.all(
                                  color: isHighlighted
                                      ? colorScheme.primary
                                      : Colors.white.withValues(alpha: 0.18),
                                  width: isHighlighted ? 3.0 : 1.2,
                                ),
                              ),
                              child: ClipOval(
                                child: _buildBubbleContent(rb.item, rb.diameter),
                              ),
                            ),
                          ),
                        );
                      }).toList(),
                    ),
                  ),
                ),

                // 2. Top Navigation Bar & Category Filter Pills
                Positioned(
                  top: 12,
                  left: 16,
                  right: 16,
                  child: Column(
                    mainAxisSize: MainAxisSize.min,
                    children: [
                      Row(
                        children: [
                          IconButton.filledTonal(
                            icon: const Icon(Icons.arrow_back_rounded),
                            tooltip: 'Back',
                            onPressed: () => Navigator.of(context).pop(),
                          ),
                          const SizedBox(width: 12),
                          Expanded(
                            child: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                Text(
                                  context.tr('bubble_nav_title'),
                                  style: AttuneTypography.soraHeading(
                                    fontSize: 18,
                                    color: Colors.white,
                                    fontWeight: FontWeight.w700,
                                  ),
