import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:attune_app/services/tilt_service.dart';
import 'package:attune_app/services/settings_service.dart';
import 'package:attune_app/models/for_you_mix.dart';
import 'package:attune_app/models/track_item.dart';
import 'package:attune_app/widgets/autogenerated_mix_cover.dart';
import 'package:attune_app/widgets/m3_expressive_mix_collage.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  group('TiltService Tests', () {
    test('Initializes with neutral tilt and dormant state', () {
      final tilt = TiltService.instance;
      expect(tilt.tiltX, equals(0.0));
      expect(tilt.tiltY, equals(0.0));
      expect(tilt.activeViewersCount, equals(0));
    });

    test('Updates tilt accurately via desktop pointer tracking', () {
      final tilt = TiltService.instance;
      // Center coordinates
      tilt.updatePointer(const Offset(100, 100), const Size(200, 200));
      expect(tilt.tiltX, closeTo(0.0, 0.001));
      expect(tilt.tiltY, closeTo(0.0, 0.001));

      // Top-left coordinates: local (0, 0) in 200x200 box -> normalized (-1, -1)
      tilt.updatePointer(const Offset(0, 0), const Size(200, 200));
      expect(tilt.tiltX, closeTo(-1.0, 0.001));
      expect(tilt.tiltY, closeTo(-1.0, 0.001));

      // Bottom-right coordinates: local (200, 200) -> normalized (1, 1)
      tilt.updatePointer(const Offset(200, 200), const Size(200, 200));
      expect(tilt.tiltX, closeTo(1.0, 0.001));
      expect(tilt.tiltY, closeTo(1.0, 0.001));

      // Reset pointer centers tilt
      tilt.resetPointer();
      expect(tilt.tiltX, equals(0.0));
      expect(tilt.tiltY, equals(0.0));
    });

    test('Manages viewer registration and stage visibility lifecycle', () {
      final tilt = TiltService.instance;
      tilt.registerViewer();
      expect(tilt.activeViewersCount, equals(1));

      tilt.setStageInView(true);
      expect(tilt.isStageInView, isTrue);

      tilt.setStageInView(false);
      expect(tilt.isStageInView, isFalse);

      tilt.unregisterViewer();
      expect(tilt.activeViewersCount, equals(0));
    });
  });

  group('ForYouDesignMode & SettingsService Tests', () {
    test('ForYouDesignMode has valid labels', () {
      expect(ForYouDesignMode.m3Expressive.label, equals('M3 Expressive'));
      expect(ForYouDesignMode.betaCards.label, equals('Beta Cards'));
    });

    test('SettingsService updates and retains ForYouDesignMode', () {
      final settings = SettingsService.instance;
      settings.setForYouDesignMode(ForYouDesignMode.betaCards);
      expect(settings.forYouDesignMode, equals(ForYouDesignMode.betaCards));

      settings.setForYouDesignMode(ForYouDesignMode.m3Expressive);
      expect(settings.forYouDesignMode, equals(ForYouDesignMode.m3Expressive));
    });
  });

  group('M3ExpressiveMixCollage Widget Tests', () {
    testWidgets('Renders M3ExpressiveMixCollage hero and bubbles with fallback art', (tester) async {
      final sampleMix = ForYouMix(
        id: 'test_mix_1',
        title: 'Morning Energy',
        subtitle: 'Brisk & Upbeat Jams',
        vibeCategory: 'energy',
        tracks: [
          const TrackItem(
            id: 't1',
            title: 'Electric Horizon',
            artist: 'SynthWave Core',
            album: 'Neon Grid',
            duration: Duration(seconds: 210),
            filePath: '/music/t1.mp3',
            bpm: 128.0,
            musicalKey: 'C Major',
          ),
          const TrackItem(
            id: 't2',
            title: 'Summer Breeze',
            artist: 'Acoustic Soul',
            album: 'Chill Acoustic',
            duration: Duration(seconds: 255),
            filePath: '/music/t2.mp3',
            bpm: 110.0,
            musicalKey: 'G Major',
          ),
        ],
        primaryColor: const Color(0xFF6750A4),
        secondaryColor: const Color(0xFFD0BCFF),
        artStyle: ForYouArtStyle.geometricPulse,
        badge: 'MIX 01',
      );

      bool playPressed = false;

      await tester.pumpWidget(
        MaterialApp(
          home: Scaffold(
            body: SingleChildScrollView(
              child: M3ExpressiveMixCollage(
                mix: sampleMix,
                onPlay: () => playPressed = true,
              ),
            ),
          ),
        ),
      );

      await tester.pumpAndSettle();

      // Verify title and dynamic artist subtitle are rendered
      expect(find.text('Morning Energy'), findsOneWidget);
      expect(find.text('SynthWave Core, Acoustic Soul'), findsOneWidget);

      // Verify Play button is present and triggers callback
      expect(find.byIcon(Icons.play_arrow_rounded), findsOneWidget);
      await tester.tap(find.byIcon(Icons.play_arrow_rounded));
      await tester.pump();
      expect(playPressed, isTrue);

      // Verify fallback procedural covers are generated for tracks without images
      expect(find.byType(AutogeneratedMixCover), findsWidgets);

      // Verify tooltips with album names exist for navigating to album
      expect(find.byTooltip('View album: Neon Grid'), findsOneWidget);
    });
  });
}
